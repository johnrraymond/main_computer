"""Continual NanoJev primary-only consensus curriculum.

This is the deliberate rollback from explicit meta-analysis training.

The optimizer population is exactly the primary population that was already
working inside the consensus-heavy meta experiment:
  * 108 consensus questions
  *   4 triad rehearsal questions
  *   4 dictionary-definition rehearsal questions
  *   4 English/code rehearsal questions

Total: 120 primary questions per cycle, trained for the same default 32
ordinary cross-entropy optimizer steps. No candidate-correctness questions,
primary-error-prediction questions, meta caches, relative arbitration, or meta
evaluation are generated by this script.

The script creates a separate experiment lineage. By default it cuts over from
the latest committed checkpoint of the existing consensus-heavy meta experiment,
including its optimizer moments and RNG state. --source-checkpoint may be used to
start from a specific committed checkpoint in that source experiment.

Training remains ordinary cross entropy on the generic
Question -> Candidate -> ObjectPath boundary with the frozen Qwen backbone.
"""

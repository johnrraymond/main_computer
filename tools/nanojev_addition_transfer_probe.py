#!/usr/bin/env python3
"""Controlled length/sign/cancellation transfer from the v2 signed-stage checkpoint.

Six independent, trainable probes start from the *same* passed digit-token
checkpoint. Only TRAIN labels are generated by Python addition. The neural
forward pass has no scripted arithmetic or oracle. DEV operands are held out
by an order/sign-invariant magnitude-pair split. No TEST data are loaded.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import random

import torch
from torch import nn

from tools import nanojev_addition_curriculum as base

SCHEMA = 'nanojev.addition-transfer-probe.v1'
BRANCHES = (
    'positive_3digit', 'positive_4digit',
    'opposite_3digit_away', 'opposite_4digit_away',
    'near_4digit', 'zero_4digit',
)
GROUPS = {
    'positive_3digit': ('no_carry', 'carry'),
    'positive_4digit': ('no_carry', 'carry'),
    'opposite_3digit_away': ('positive_result', 'negative_result'),
    'opposite_4digit_away': ('positive_result', 'negative_result'),
    'near_4digit': ('positive_residual', 'negative_residual'),
    'zero_4digit': ('positive_first', 'negative_first'),
}
# Largest absolute result < 20000 -> 5 output decimal places.
OUTPUT_DIGITS = 5
ORIGINAL_STAGES = ('atomic', 'no_carry', 'carry', 'signed')


def write_json(path, obj):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + '.tmp')
    temp.write_text(json.dumps(obj, indent=2, sort_keys=True) + '\n', encoding='utf-8')
    os.replace(temp, path)


def save_state(path, obj):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix('.tmp')
    torch.save(obj, temp)
    os.replace(temp, path)


def magnitude_pair(a, b):
    return tuple(sorted((abs(int(a)), abs(int(b)))))


def has_carry(a, b):
    # Dataset classification only. No model forward pass uses this function.
    carry = 0
    while a or b:
        carry = (a % 10 + b % 10 + carry) // 10
        if carry:
            return True
        a //= 10
        b //= 10
    return False


def candidate(rng, branch, category):
    lo, hi = (100, 999) if '3digit' in branch else (1000, 9999)
    if branch.startswith('positive'):
        a, b = rng.randint(lo, hi), rng.randint(lo, hi)
        group = 'carry' if has_carry(a, b) else 'no_carry'
        return (a, b) if group == category else None
    if branch.startswith('opposite'):
        a, b = rng.randint(lo, hi), rng.randint(lo, hi)
        if abs(a - b) < .25 * max(a, b):
            return None
        group = 'positive_result' if a > b else 'negative_result'
        if group != category:
            return None
        pair = (a, -b)
        return pair if rng.getrandbits(1) else pair[::-1]
    if branch == 'near_4digit':
        a = rng.randint(lo, hi)
        delta = rng.randint(1, max(1, a // 100))
        # Residual sign controls the group independently of input order/sign.
        target_sign = 1 if category == 'positive_residual' else -1
        first_sign = 1 if rng.getrandbits(1) else -1
        aa = first_sign * a
        bb = -aa + target_sign * delta
        if not (lo <= abs(bb) <= hi):
            return None
        pair = (aa, bb)
        return pair if rng.getrandbits(1) else pair[::-1]
    if branch == 'zero_4digit':
        mag = rng.randint(lo, hi)
        first = mag if category == 'positive_first' else -mag
        return first, -first
    raise ValueError(f'UNKNOWN_BRANCH:{branch}')


def make_dataset(branch, split, seed, per_group):
    """Returns unique, truly held-out unordered absolute-operand pairs.

    Sharing a numeric operand across splits is allowed; sharing its *pair* is
    forbidden. Sign flips and operand order cannot leak the held-out answer.
    """
    if branch not in BRANCHES or split not in ('train', 'dev', 'test') or per_group < 1:
        raise ValueError('TRANSFER_INVALID_DATASET')
    rows, used = [], set()
    for category in GROUPS[branch]:
        rng = random.Random(f'{seed}:{branch}:{split}:{category}')
        added = 0
        for _ in range(per_group * 5000):
            pair = candidate(rng, branch, category)
            if pair is None:
                continue
            a, b = pair
            key = magnitude_pair(a, b)
            if key in used or base.pair_fold(*key, seed) != split:
                continue
            used.add(key)
            rows.append((a, b, a + b, category))
            added += 1
            if added >= per_group:
                break
        if added != per_group:
            raise RuntimeError(f'TRANSFER_DATA_EXHAUSTED:{branch}:{split}:{category}:{added}')
    random.Random(f'{seed}:shuffle:{branch}:{split}').shuffle(rows)
    return {'x': torch.tensor([(a, b) for a, b, _, _ in rows], dtype=torch.long),
            'y': torch.tensor([y for _, _, y, _ in rows], dtype=torch.long),
            'groups': [group for _, _, _, group in rows],
            'branch': branch, 'split': split, 'kind': 'held_out_magnitude_pairs'}


@torch.no_grad()
def evaluate(model, data, device, batch_size, tolerance):
    model.eval()
    digits, regression = [], []
    for x in data['x'].split(batch_size):
        x = x.to(device)
        p = model(x)
        digits.append(base.decode(p, OUTPUT_DIGITS).cpu())
        regression.append((p['ratio'] * x.abs().amax(-1).clamp(min=1).float()).cpu())
    digit = torch.cat(digits)
    truth = data['y']
    groups = data['groups']
    return {'digit': base.score(digit, truth, groups, tolerance),
            'regression': base.score(torch.cat(regression), truth, groups, tolerance),
            'digit_exact': float((digit == truth).float().mean()),
            'predicted_zero_fraction': float((digit == 0).float().mean()),
            'true_zero_fraction': float((truth == 0).float().mean()),
            'false_zero_count': int(((digit == 0) & (truth != 0)).sum()),
            'branch': data['branch'], 'split': data['split'], 'kind': data['kind']}


def old_retention_sets(seed, options):
    # There is deliberately no reference to any TEST dataset in training.
    return {stage: base.make_stage(stage, 'dev', seed, options['dev_per_group'])
            for stage in ORIGINAL_STAGES}


@torch.no_grad()
def evaluate_retention(model, datasets, device, batch_size, tolerance):
    return {stage: base.evaluate(model, data, device, batch_size, tolerance)
            for stage, data in datasets.items()}


def gate(dev, retention, threshold):
    current = min(dev['digit'][c]['rate'] for c in GROUPS[dev['branch']])
    prior = {s: min(v['rate'] for k, v in m['digit'].items() if k != 'all')
             for s, m in retention.items()}
    ok_prior = all(value >= (1.0 if stage == 'atomic' else threshold)
                   for stage, value in prior.items())
    return {'pass': current >= threshold and ok_prior,
            'min_dev': current, 'min_retention': min(prior.values()),
            'retention_by_stage': prior, 'threshold': threshold}


def read_signed_checkpoint(source):
    source = Path(source).expanduser().resolve()
    if not source.is_file():
        raise FileNotFoundError(f'TRANSFER_SIGNED_CHECKPOINT_MISSING:{source}')
    checkpoint_hash = base.sha256(source)
    ck = torch.load(source, map_location='cpu', weights_only=True)
    if (ck.get('schema') != base.SCHEMA + '.passed'
            or ck.get('stage') != 'signed' or ck.get('arm') != 'digit_tokens'
            or not ck.get('result', {}).get('gate', {}).get('pass')):
        raise RuntimeError('TRANSFER_REQUIRES_SIGNED_PASSED_CHECKPOINT')
    ident = ck.get('identity')
    if not isinstance(ident, dict) or ident.get('schema') != base.SCHEMA:
        raise RuntimeError('TRANSFER_SOURCE_IDENTITY_INVALID')
    if ident.get('source_sha256') != base.sha256(base.__file__):
        raise RuntimeError('TRANSFER_BASE_CURRICULUM_SOURCE_DRIFT')
    opts = ident.get('options')
    if not isinstance(opts, dict) or not all(k in opts for k in (
            'seed', 'width', 'heads', 'layers', 'rounds', 'dev_per_group')):
        raise RuntimeError('TRANSFER_SOURCE_OPTIONS_MISSING')
    # Validate model compatibility before creating any output files.
    model = base.AdditionNet('digit_tokens', opts['width'], opts['heads'],
                             opts['layers'], opts['rounds'], opts['seed'])
    model.load_state_dict(ck['model'], strict=True)
    return ck, checkpoint_hash


def experiment_identity(args, checkpoint_hash, ck):
    attrs = ('seed', 'lr', 'batch_size', 'eval_batch_size', 'train_per_group',
             'dev_per_group', 'replay_fraction', 'threshold', 'tolerance',
             'probe_every', 'cpu_threads', 'branches')
    return {'schema': SCHEMA, 'runner_sha256': base.sha256(__file__),
            'source_checkpoint_sha256': checkpoint_hash,
            'source_checkpoint': str(Path(args.signed_checkpoint).expanduser().resolve()),
            'source_schema': ck['identity']['schema'],
            'source_options': ck['identity']['options'],
            'options': {k: getattr(args, k) for k in attrs},
            'policy': 'independent learned transfer probes; exact held-out magnitude pairs; original signed model kept immutable; TEST never evaluated'}


def snapshot(model, optimizer, rng, step, best_rank, best_step, ident, branch, best_record):
    return {'schema': SCHEMA + '.state', 'identity': ident,
            'branch': branch, 'step': step, 'best_rank': list(best_rank),
            'best_step': best_step, 'best_record': best_record,
            'model': model.state_dict(), 'optimizer': optimizer.state_dict(),
            'sample_rng': rng.get_state(), 'torch_rng': torch.get_rng_state(),
            'cuda_rng': torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None}


def restore(path, model, optimizer, rng, ident, branch):
    st = torch.load(path, map_location='cpu', weights_only=True)
    if (st.get('schema') != SCHEMA + '.state' or st.get('identity') != ident
            or st.get('branch') != branch):
        raise RuntimeError('TRANSFER_RESUME_IDENTITY_MISMATCH')
    model.load_state_dict(st['model'], strict=True)
    optimizer.load_state_dict(st['optimizer'])
    rng.set_state(st['sample_rng'])
    torch.set_rng_state(st['torch_rng'])
    if st['cuda_rng'] is not None and torch.cuda.is_available():
        torch.cuda.set_rng_state_all(st['cuda_rng'])
    return st


def train_branch(branch, idx, args, ck, ident, root, retained, source_hash):
    folder = root / 'branches' / branch
    latest = folder / 'latest.pt'
    if not args.resume and folder.exists() and any(folder.iterdir()):
        raise FileExistsError(f'TRANSFER_BRANCH_OVERWRITE_REFUSED:{branch}')
    folder.mkdir(parents=True, exist_ok=True)
    opts = ck['identity']['options']
    model = base.AdditionNet('digit_tokens', opts['width'], opts['heads'],
                             opts['layers'], opts['rounds'], opts['seed']).to(args.device)
    model.load_state_dict(ck['model'], strict=True)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=0.)
    # All branches receive identical starting weights, independently trained.
    torch.manual_seed(args.seed + 10000 + idx)
    rng = torch.Generator(device='cpu').manual_seed(args.seed + 20000 + idx)
    start, best_rank, best_step, best_record = 0, (-1., -1., -1.), 0, None
    if args.resume:
        if not latest.is_file():
            raise FileNotFoundError(f'TRANSFER_RESUME_STATE_MISSING:{branch}')
        state = restore(latest, model, optimizer, rng, ident, branch)
        start, best_rank, best_step, best_record = (state['step'],
                       tuple(state['best_rank']), state['best_step'], state['best_record'])
    train = make_dataset(branch, 'train', args.seed, args.train_per_group)
    dev = make_dataset(branch, 'dev', args.seed, args.dev_per_group)
    replay = [base.make_stage(stage, 'train', opts['seed'], args.replay_per_stage)
              for stage in ORIGINAL_STAGES] if args.replay_fraction else []
    if start == 0:
        baseline = evaluate(model, dev, args.device, args.eval_batch_size, args.tolerance)
        old = evaluate_retention(model, retained, args.device, args.eval_batch_size, args.tolerance)
        write_json(folder / 'baseline.json', {'dev': baseline, 'retention': old,
                                                'gate': gate(baseline, old, args.threshold)})
    for step in range(start + 1, args.steps + 1):
        model.train()
        ids = torch.randint(len(train['y']), (args.batch_size,), generator=rng)
        xx = train['x'].index_select(0, ids)
        yy = train['y'].index_select(0, ids)
        if replay:
            count = round(args.batch_size * args.replay_fraction)
            # Balanced cross-stage rehearsal instead of losing signed examples.
            if count:
                r = replay[(step - 1) % len(replay)]
                ids_old = torch.randint(len(r['y']), (count,), generator=rng)
                xx[:count] = r['x'].index_select(0, ids_old)
                yy[:count] = r['y'].index_select(0, ids_old)
        x, y = xx.to(args.device), yy.to(args.device)
        out = model(x)
        loss = base.objective(out, x, y, OUTPUT_DIGITS)
        if not torch.isfinite(loss):
            raise FloatingPointError(f'TRANSFER_NONFINITE_LOSS:{branch}:{step}')
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), 1., error_if_nonfinite=True)
        optimizer.step()
        if step % args.probe_every and step != args.steps:
            continue
        train_metrics = evaluate(model, train, args.device, args.eval_batch_size, args.tolerance)
        dev_metrics = evaluate(model, dev, args.device, args.eval_batch_size, args.tolerance)
        retained_metrics = evaluate_retention(model, retained, args.device,
                                               args.eval_batch_size, args.tolerance)
        g = gate(dev_metrics, retained_metrics, args.threshold)
        rank = (g['min_dev'], g['min_retention'], dev_metrics['digit']['all']['rate'])
        record = {'branch': branch, 'step': step, 'train': train_metrics,
                  'dev': dev_metrics, 'retention': retained_metrics, 'gate': g}
        if rank > best_rank:
            best_rank, best_step, best_record = rank, step, record
            save_state(folder / 'best.pt', {'schema': SCHEMA + '.best',
                      'identity': ident, 'branch': branch, 'step': step,
                      'model': model.state_dict(), 'report': record})
            write_json(folder / 'best.json', record)
        print(f'ADDITION_TRANSFER branch={branch} step={step}/{args.steps} '
              f'loss={float(loss.detach()):.5f} '
              f'TRAIN={train_metrics["digit"]["all"]["rate"]:.4f} '
              f'DEV_min={g["min_dev"]:.4f} '
              f'DEV_all={dev_metrics["digit"]["all"]["rate"]:.4f} '
              f'RETAIN_min={g["min_retention"]:.4f} '
              f'bestStep={best_step} gate={"PASS" if g["pass"] else "FAIL"}', flush=True)
        save_state(latest, snapshot(model, optimizer, rng, step, best_rank,
                                    best_step, ident, branch, best_record))
        # Do not break on passing the gate: capture the fixed-budget trajectory
        # and whether skills degrade later. A passing best checkpoint is kept.
    if not latest.exists():
        raise RuntimeError('TRANSFER_NO_PROBES_COMPLETED')
    if base.sha256(args.signed_checkpoint) != source_hash:
        raise RuntimeError('TRANSFER_CHECKPOINT_MUTATED')
    baseline = json.loads((folder / 'baseline.json').read_text(encoding='utf-8'))
    return {'branch': branch, 'best_step': best_step,
            'gate': best_record['gate'],
            'baseline_min_dev': baseline['gate']['min_dev'],
            'best_dev_categories': {c: best_record['dev']['digit'][c]['rate']
                                    for c in GROUPS[branch]},
            'best_train_accuracy': best_record['train']['digit']['all']['rate'],
            'best_regression_accuracy': best_record['dev']['regression']['all']['rate'],
            'best_predicted_zero_fraction': best_record['dev']['predicted_zero_fraction'],
            'best_false_zero_count': best_record['dev']['false_zero_count'],
            'baseline_report': str(folder / 'baseline.json'),
            'best_report': str(folder / 'best.json')}


def run(args):
    if args.device == 'cuda' and not torch.cuda.is_available():
        raise RuntimeError('TRANSFER_CUDA_UNAVAILABLE')
    if not (0 < args.lr < 1 and 0 < args.threshold <= 1 and
            0 < args.tolerance < 1 and 0 <= args.replay_fraction < 1 and
            args.steps > 0 and args.probe_every > 0 and
            args.batch_size > 0 and args.eval_batch_size > 0 and
            args.train_per_group > 0 and args.dev_per_group > 0 and
            args.replay_per_stage > 0 and args.cpu_threads > 0):
        raise ValueError('TRANSFER_INVALID_OPTIONS')
    branches = args.branches.split(',')
    if not branches or len(branches) != len(set(branches)) or any(b not in BRANCHES for b in branches):
        raise ValueError('TRANSFER_INVALID_BRANCHES')
    args.signed_checkpoint = Path(args.signed_checkpoint).expanduser().resolve()
    ck, source_hash = read_signed_checkpoint(args.signed_checkpoint)
    torch.set_num_threads(args.cpu_threads)
    ident = experiment_identity(args, source_hash, ck)
    root = Path(args.output).expanduser().resolve()
    cfg = root / 'config.json'
    if not args.resume:
        if root.exists() and any(root.iterdir()):
            raise FileExistsError('TRANSFER_OUTPUT_OVERWRITE_REFUSED')
        root.mkdir(parents=True, exist_ok=True)
        write_json(cfg, ident)
    elif not cfg.is_file() or json.loads(cfg.read_text(encoding='utf-8')) != ident:
        raise RuntimeError('TRANSFER_CONFIG_DRIFT')
    retained = old_retention_sets(ck['identity']['options']['seed'],
                                   ck['identity']['options'])
    result = {branch: train_branch(branch, i, args, ck, ident, root,
                                   retained, source_hash)
              for i, branch in enumerate(branches)}
    write_json(root / 'summary.json', {'schema': SCHEMA + '.summary',
               'source_checkpoint_sha256': source_hash, 'branches': result,
               'TEST': None, 'hybridlink_certified': False})
    print('ADDITION_TRANSFER_SUMMARY=' + json.dumps({b: {
        'best_step': d['best_step'], 'DEV_min': d['gate']['min_dev'],
        'baseline_min': d['baseline_min_dev'],
        'categories': d['best_dev_categories'],
        'retention_min': d['gate']['min_retention'],
        'gate': 'PASS' if d['gate']['pass'] else 'FAIL'}
        for b, d in result.items()}, sort_keys=True), flush=True)
    print('ADDITION_SOURCE_IMMUTABLE=TRUE TEST_UNTOUCHED=TRUE HYBRIDLINK_UNCHANGED=TRUE', flush=True)
    return result


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--signed-checkpoint', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--device', choices=('cpu', 'cuda'), default='cuda')
    p.add_argument('--branches', default=','.join(BRANCHES))
    p.add_argument('--steps', type=int, default=1500, help='TOTAL steps per independent branch')
    p.add_argument('--probe-every', type=int, default=250)
    p.add_argument('--batch-size', type=int, default=128)
    p.add_argument('--eval-batch-size', type=int, default=256)
    p.add_argument('--train-per-group', type=int, default=768)
    p.add_argument('--dev-per-group', type=int, default=128)
    p.add_argument('--replay-per-stage', type=int, default=128)
    p.add_argument('--replay-fraction', type=float, default=.25)
    p.add_argument('--threshold', type=float, default=.80)
    p.add_argument('--tolerance', type=float, default=.05)
    p.add_argument('--seed', type=int, default=20261024)
    p.add_argument('--lr', type=float, default=.001)
    p.add_argument('--cpu-threads', type=int, default=4)
    p.add_argument('--resume', action='store_true')
    return p


def main(argv=None):
    return run(parser().parse_args(argv))


if __name__ == '__main__':
    main()

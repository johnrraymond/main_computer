#!/usr/bin/env python3
"""Hawk-Dove Gaussian HybridAgent analogue: activation + self-conditioned recursion.

Phase 1 (activation): learn HybridLink's next-input embedding using four
visible count*payoff partial products as TRAIN-only intermediate supervision.
Phase 2 (self-conditioned): repeatedly consume *predicted*, never teacher,
latent embeddings and train X/Y using the original Gaussian density decoder.

The original numeric encoder, recurrent core, Gaussian banks and decoder are
frozen. Zero reasoning steps call the original model verbatim. This is a small
numerical analogue, NOT the transformer KV-cache implementation of HybridAgent.
Historical DEV/TEST have already been seen; TEST here is exploratory only.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import math
from pathlib import Path

import torch
from torch import nn
from torch.nn import functional as F

from tools import nanojev_hawk_dove_gaussian_population_blind_matrix as blind
from tools import nanojev_hawk_dove_gaussian_population_conditional as gauss

SCHEMA = 'nanojev.hawk-dove.gaussian-hybrid-agent.v1'
DEPTHS = (0, 1, 2, 4, 8)


def sha256_file(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def partial_products(visible):
    """Four oracle-free intermediate multiplications, derived ONLY from visible X.

    Features: a/TOTAL, b/TOTAL, hh/B, hd/B, dh/B, dd/B, eight tier flags.
    The two partial sums never enter the inference path as oracle answers.
    """
    if visible.shape[-1] != blind.INPUT_DIM:
        raise ValueError('HYBRID_VISIBLE_FEATURE_DIMENSION_DRIFT')
    return torch.stack((visible[:, 0] * visible[:, 2],
                        visible[:, 1] * visible[:, 3],
                        visible[:, 0] * visible[:, 4],
                        visible[:, 1] * visible[:, 5]), dim=1)


class HybridLink(nn.Module):
    """Hidden-state -> next INPUT embedding (not a numeric-answer correction)."""
    def __init__(self, hidden):
        super().__init__()
        self.net = nn.Sequential(nn.LayerNorm(hidden), nn.Linear(hidden, hidden),
                                 nn.GELU(), nn.Linear(hidden, hidden))
        with torch.no_grad():
            self.net[-1].weight.zero_()
            self.net[-1].bias.zero_()

    def forward(self, hidden):
        return self.net(hidden)


class GaussianHybridAgent(nn.Module):
    """Re-enter the SAME pretrained encoder's second hidden layer.

    Every recursive step holds the original problem embedding fixed, combines
    it with HybridLink's generated feedback, and applies shared pretrained
    encoder[2]. Zero-step output remains bitwise the original Gaussian output.
    """
    def __init__(self, frozen_reference, seed, teacher_scale=0.35):
        super().__init__()
        self.reference = frozen_reference
        for parameter in self.reference.parameters():
            parameter.requires_grad_(False)
        self.reference.eval()
        self.hidden = frozen_reference.hidden
        self.bins = frozen_reference.bins
        self.link = HybridLink(self.hidden)
        rng = torch.Generator(device='cpu').manual_seed(int(seed) + 731)
        basis = torch.randn(self.hidden, 4, generator=rng)
        basis, _ = torch.linalg.qr(basis, mode='reduced')
        self.register_buffer('teacher_basis', basis.T.contiguous() *
                             (float(teacher_scale) * math.sqrt(self.hidden / 4)))

    def train(self, mode=True):
        super().train(mode)
        self.reference.eval()  # frozen even while recurrent HybridLink trains
        return self

    def embedding(self, features):
        first = self.reference.encoder
        initial = F.silu(first[0](features))
        hidden = F.silu(first[2](initial))
        return initial, hidden

    def teacher_delta(self, visible):
        return partial_products(visible) @ self.teacher_basis

    def generated_delta(self, visible):
        _, hidden = self.embedding(visible)
        return self.link(hidden)

    def latent(self, visible, depth, intervention='normal'):
        if depth < 0 or depth > 64 or intervention not in ('normal', 'disabled', 'shuffled'):
            raise ValueError('HYBRID_INVALID_DEPTH_OR_INTERVENTION')
        initial, hidden = self.embedding(visible)
        for _ in range(depth):
            feedback = self.link(hidden)  # generated by the model, not a teacher
            if intervention == 'disabled':
                feedback = feedback * 0.
            elif intervention == 'shuffled':
                feedback = feedback.roll(1, dims=0)
            # HybridLink feeds an INPUT embedding to the shared reasoning layer.
            hidden = F.silu(self.reference.encoder[2](initial + feedback))
        return hidden

    def forward(self, features, depth=0, intervention='normal'):
        if depth == 0:
            return self.reference(features)  # exact single-pass baseline
        hidden = self.latent(features, depth, intervention)
        model = self.reference
        location = model.encoder[4](hidden).sigmoid()
        sigma = model.log_proposal_sigma.exp().clamp(min=.3, max=20.)
        delta = (model.centers.reshape(1, 1, -1) - location.unsqueeze(-1)) * model.bins
        logits = -.5 * (delta / sigma.reshape(1, 2, 1)).square() + model.bank_log_gains
        masses = F.softmax(logits, dim=-1)
        density = masses.reshape(-1, model.banks) @ model.basis
        return density.reshape(-1, 2, model.bins)


class FixedDepthView(nn.Module):
    def __init__(self, agent, depth, intervention='normal'):
        super().__init__()
        self.agent = agent
        self.depth = depth
        self.intervention = intervention
        self.bins = agent.bins

    def forward(self, features):
        return self.agent(features, self.depth, self.intervention)


def activation_loss(agent, batch):
    predicted = agent.generated_delta(batch)
    target = agent.teacher_delta(batch)
    # Cosine alignment is undefined for zero arithmetic examples; safe epsilon.
    mse = F.mse_loss(predicted, target)
    cosine = 1 - F.cosine_similarity(predicted, target, dim=-1, eps=1e-8).mean()
    return mse + .02 * cosine, {'mse': float(mse.detach()),
                               'cosine_loss': float(cosine.detach())}


def numerical_loss(agent, features, truth, domain, bins, sigma_bins, depth):
    density = agent(features, depth)
    target = gauss.normalized_target(truth, domain, bins, sigma_bins)
    kl = (target * (target.clamp_min(1e-12).log() -
                    density.clamp_min(1e-12).log())).sum(-1).mean()
    mse = bins * (density - target).square().mean()
    predicted = gauss.numeric_decode(density, domain)
    location = torch.stack([(truth[:, j] - domain[j][0]) /
                            (domain[j][1] - domain[j][0]) for j in range(2)], 1)
    pred_loc = torch.stack([(predicted[:, j] - domain[j][0]) /
                            (domain[j][1] - domain[j][0]) for j in range(2)], 1)
    # Strict near-zero relative errors remain visible, not masked by a 10k floor.
    relative = torch.log1p((predicted - truth).abs() /
                           (truth.abs() * .05).clamp_min(1.)).mean()
    loss = kl + mse + 10 * (pred_loc - location).square().mean() + .004 * relative
    return loss


def phase_depth(step, total):
    # Deterministic 1/2/4/8 curriculum; all phase-two inputs are self-generated.
    return (1, 2, 4, 8)[min(3, (4 * (step - 1)) // total)]


def balanced_ids(data, batch_size, generator, device):
    selected = []
    for index, tier in enumerate(blind.TIERS):
        count = batch_size // len(blind.TIERS) + int(index < batch_size % len(blind.TIERS))
        if not count:
            continue
        pool = data['tier_indices'][tier]
        draws = torch.randint(len(pool), (count,), generator=generator)
        selected.append(pool[draws.to(pool.device)])
    return torch.cat(selected).to(device)


def score(agent, split, domain, args, depth, intervention='normal'):
    view = FixedDepthView(agent, depth, intervention)
    metrics = gauss.evaluate(view, split, domain, args.target_sigma_bins,
                             batch_size=args.eval_batch_size,
                             relative_tolerance=args.tolerance)
    rank = blind._rank(metrics)
    return metrics, rank


def _identity(args, checkpoint_identity, manifest, sha):
    return {'schema': SCHEMA, 'source_sha256': sha,
            'source_identity': checkpoint_identity,
            'matrix_hashes': manifest['matrix_hashes'],
            'warmup_steps': args.warmup_steps, 'planned_self_conditioned_steps': args.steps,
            'seed': args.seed,
            'batch_size': args.batch_size, 'probe_every': args.probe_every,
            'warmup_lr': args.warmup_lr, 'lr': args.lr,
            'teacher_scale': args.teacher_scale,
            'tolerance': args.tolerance,
            'max_depth': 8,
            'source_frozen': True,
            'feedback':'hidden_to_next_input_embedding_shared_second_layer',
            'teacher':'visible_partial_products_train_only',
            'test_policy':'EXPLORATORY_PREVIOUSLY_EXAMINED_SPLITS'}


def _save_latest(path, agent, warm_opt, self_opt, generator, warm_step,
                 self_step, best_rank, best_depth, best_step, history, identity):
    gauss._atomic_save(path, {
        'schema': SCHEMA + '.progress', 'identity': identity,
        'link': copy.deepcopy(agent.link.state_dict()),
        'warm_optimizer': warm_opt.state_dict(), 'self_optimizer': self_opt.state_dict(),
        'sampler_rng': generator.get_state(), 'torch_rng': torch.get_rng_state(),
        'cuda_rng': torch.cuda.get_rng_state_all() if torch.cuda.is_available() else [],
        'warm_step': warm_step, 'self_step': self_step,
        'best_rank': best_rank, 'best_depth': best_depth, 'best_step': best_step,
        'history': history})


def _restore(progress, agent, warm_opt, self_opt, generator):
    agent.link.load_state_dict(progress['link'], strict=True)
    warm_opt.load_state_dict(progress['warm_optimizer'])
    self_opt.load_state_dict(progress['self_optimizer'])
    generator.set_state(progress['sampler_rng'])
    torch.set_rng_state(progress['torch_rng'])
    if progress['cuda_rng']:
        if not torch.cuda.is_available() or len(progress['cuda_rng']) != torch.cuda.device_count():
            raise RuntimeError('HYBRID_CUDA_RNG_TOPOLOGY_DRIFT')
        torch.cuda.set_rng_state_all(progress['cuda_rng'])


def _validate(args):
    if any(v < 1 for v in (args.warmup_steps, args.steps, args.probe_every,
                            args.batch_size, args.eval_batch_size, args.cpu_threads)):
        raise ValueError('HYBRID_INVALID_TRAINING_DIMENSIONS')
    if not (0 < args.lr <= 1 and 0 < args.warmup_lr <= 1 and
            0 < args.teacher_scale <= 5 and 0 < args.tolerance < 1):
        raise ValueError('HYBRID_INVALID_OPTIMIZATION')
    if (args.stop_after is not None and not 1 <= args.stop_after <= args.steps) or (
        args.warmup_stop_after is not None and not 1 <= args.warmup_stop_after <= args.warmup_steps):
        raise ValueError('HYBRID_INVALID_PAUSE_BOUNDARY')
    if args.device == 'cuda' and not torch.cuda.is_available():
        raise RuntimeError('HYBRID_CUDA_UNAVAILABLE')


def train(args):
    _validate(args)
    torch.set_num_threads(args.cpu_threads)
    device = torch.device(args.device)
    source = args.reference_checkpoint.resolve()
    source_hash = sha256_file(source)
    checkpoint = torch.load(source, map_location='cpu', weights_only=True)
    if checkpoint.get('schema') != blind.SCHEMA:
        raise ValueError('HYBRID_REFERENCE_CHECKPOINT_SCHEMA_DRIFT')
    ci = checkpoint['identity']
    args.target_sigma_bins = ci['target_sigma_bins']
    original = blind.BlindDensityNetwork(ci['banks'], ci['grid_bins'], ci['seed'],
                                         ci['hidden'])
    original.load_state_dict(checkpoint['model'], strict=True)
    data_args = argparse.Namespace(**ci)
    splits, domain, manifest = blind._dataset(data_args, device)
    if ci['matrix_hashes'] != manifest['matrix_hashes'] or ci['domain'] != [list(d) for d in domain]:
        raise RuntimeError('HYBRID_REFERENCE_MATRIX_OR_DOMAIN_DRIFT')
    original = original.to(device)
    identity = _identity(args, ci, manifest, source_hash)
    output = args.output.expanduser().resolve()
    if args.resume:
        if (output / 'report.json').is_file():
            raise RuntimeError('HYBRID_RUN_ALREADY_FINALIZED')
        if not (output / 'latest.pt').is_file():
            raise FileNotFoundError('HYBRID_RESUME_REQUIRES_LATEST_STATE')
        state = torch.load(output / 'latest.pt', map_location='cpu', weights_only=True)
        if state.get('schema') != SCHEMA + '.progress' or state.get('identity') != identity:
            raise RuntimeError('HYBRID_RESUME_IDENTITY_DRIFT')
        if args.steps < state['self_step']:
            raise ValueError('HYBRID_RESUME_STEP_REGRESSION')
    elif output.exists() and any(output.iterdir()):
        raise FileExistsError('HYBRID_REFUSES_OUTPUT_OVERWRITE')
    if not args.resume:
        output.mkdir(parents=True, exist_ok=True)
        gauss._atomic_json(output / 'config.json', identity)
        gauss._atomic_json(output / 'matrix_split_manifest.json', manifest)
    torch.manual_seed(args.seed)
    agent = GaussianHybridAgent(original, seed=args.seed, teacher_scale=args.teacher_scale).to(device)
    warm_opt = torch.optim.AdamW(agent.link.parameters(), lr=args.warmup_lr, weight_decay=0.)
    self_opt = torch.optim.AdamW(agent.link.parameters(), lr=args.lr, weight_decay=0.)
    generator = torch.Generator(device='cpu').manual_seed(args.seed + 91)
    warm_step, self_step = 0, 0
    best_rank = None
    best_depth, best_step = None, None
    history = []
    if args.resume:
        _restore(state, agent, warm_opt, self_opt, generator)
        warm_step, self_step = state['warm_step'], state['self_step']
        best_rank, best_depth, best_step = state['best_rank'], state['best_depth'], state['best_step']
        history = state['history']

    agent.eval()
    with torch.no_grad():
        sample = splits['dev']['features'][:min(64, len(splits['dev']['rows']))]
        parity = torch.equal(original(sample), agent(sample, depth=0))
        if not parity:
            raise RuntimeError('HYBRID_ZERO_STEP_PARITY_FAILED')
    print('HYBRID_ZERO_STEP_PARITY=PASS source_frozen=TRUE', flush=True)
    baseline, base_rank = score(agent, splits['dev'], domain, args, 0)
    print(f'HYBRID_REFERENCE_DEV={base_rank[0]:.6f} checkpoint={source.name}', flush=True)
    if not args.resume:
        gauss._atomic_json(output / 'baseline.json', {'dev': baseline, 'rank':base_rank,
                  'zero_step_exact_parity': True, 'source_sha256':source_hash})

    if warm_step < args.warmup_steps:
        agent.eval()
        # Reconstruct the INITIAL all-zero-link baseline, even after a pause.
        target = agent.teacher_delta(splits['dev']['features'])
        pre_value = float(target.square().mean() + .02)
        warm_limit = min(args.warmup_steps, args.warmup_stop_after or args.warmup_steps)
        for ws in range(warm_step + 1, warm_limit + 1):
            agent.train()
            idx = balanced_ids(splits['train'], args.batch_size, generator, device)
            x = splits['train']['features'][idx]
            warm_opt.zero_grad(set_to_none=True)
            loss, _ = activation_loss(agent, x)
            if not bool(torch.isfinite(loss)):
                raise FloatingPointError('HYBRID_WARMUP_NONFINITE_LOSS')
            loss.backward()
            nn.utils.clip_grad_norm_(agent.link.parameters(), 1., error_if_nonfinite=True)
            warm_opt.step()
            warm_step = ws
            if ws % args.probe_every == 0 or ws == args.warmup_steps:
                agent.eval()
                with torch.no_grad():
                    v, _ = activation_loss(agent, splits['dev']['features'])
                    value = float(v)
                history.append({'phase':'activation','step':ws,
                                'training_loss':float(loss.detach()), 'dev_alignment_loss':value})
                print(f'HYBRID_ACTIVATION step={ws}/{args.warmup_steps} '
                      f'DEV_alignment_loss={value:.7f}', flush=True)
                _save_latest(output/'latest.pt',agent,warm_opt,self_opt,generator,
                             warm_step,self_step,best_rank,best_depth,best_step,history,identity)
        if warm_step < args.warmup_steps:
            _save_latest(output/'latest.pt',agent,warm_opt,self_opt,generator,
                         warm_step,self_step,best_rank,best_depth,best_step,history,identity)
            print(f'HYBRID_PAUSED_ACTIVATION={warm_step}/{args.warmup_steps}',flush=True)
            return {'status':'PAUSED_ACTIVATION','warm_step':warm_step,'self_step':self_step}
        agent.eval()
        with torch.no_grad():
            post, _ = activation_loss(agent, splits['dev']['features'])
            post_value = float(post)
        gate = 'PASS' if post_value < pre_value and math.isfinite(post_value) else 'FAIL'
        gauss._atomic_json(output/'activation.json',{
            'status':gate,'pre_loss':pre_value,'post_loss':post_value,
            'teacher':'four visible count*payoff products',
            'teacher_vectors_never_fed_in_phase2':True})
        print(f'HYBRID_ACTIVATION_GATE={gate} initial={pre_value:.7f} final={post_value:.7f}',flush=True)
        if gate != 'PASS':
            raise RuntimeError('HYBRID_ACTIVATION_GATE_FAILED')
        gauss._atomic_save(output/'activation.pt',{
            'schema':SCHEMA+'.activation','identity':identity,
            'link':copy.deepcopy(agent.link.state_dict()),'warm_step':warm_step})
    else:
        evidence = json.loads((output/'activation.json').read_text(encoding='utf8'))
        if evidence.get('status')!='PASS':
            raise RuntimeError('HYBRID_RESUME_ACTIVATION_NOT_CERTIFIED')
        print('HYBRID_ACTIVATION_GATE=PASS resumed_prior_evidence=VERIFIED', flush=True)

    # Stage 2 intentionally does not feed teacher embeddings, even at depth 1.
    print('HYBRID_SELF_CONDITIONING=ACTIVE depths=1,2,4,8 teacher_vectors_at_inference=FALSE',flush=True)
    self_limit = min(args.steps, args.stop_after or args.steps)
    for step in range(self_step + 1, self_limit + 1):
        depth = phase_depth(step, args.steps)
        agent.train()
        ids=balanced_ids(splits['train'], args.batch_size, generator, device)
        features = splits['train']['features'][ids]
        truth = splits['train']['numeric'][ids]
        self_opt.zero_grad(set_to_none=True)
        loss = numerical_loss(agent,features,truth,domain,ci['grid_bins'],
                              ci['target_sigma_bins'],depth)
        # Maintain arithmetic-carrying feedback while training the numerical head.
        aux, _ = activation_loss(agent, features)
        loss = loss + .002 * aux
        if not bool(torch.isfinite(loss)):
            raise FloatingPointError('HYBRID_SELF_CONDITIONED_NONFINITE_LOSS')
        loss.backward()
        grad = nn.utils.clip_grad_norm_(agent.link.parameters(),1.,error_if_nonfinite=True)
        if not bool(torch.isfinite(grad)):
            raise FloatingPointError('HYBRID_LINK_GRADIENT_NONFINITE')
        self_opt.step()
        self_step = step
        if step % args.probe_every == 0 or step == args.steps:
            agent.eval()
            with torch.no_grad():
                depth_metrics = {}
                for d in DEPTHS[1:]:
                    metrics, rank = score(agent, splits['dev'],domain,args,d)
                    depth_metrics[str(d)]={'min_joint5':rank[0],'mean_joint5':rank[1]}
                    if best_rank is None or rank > tuple(best_rank):
                        best_rank = rank
                        best_depth = d
                        best_step = step
                        gauss._atomic_save(output/'best.pt',{
                            'schema':SCHEMA+'.best','identity':identity,
                            'link':copy.deepcopy(agent.link.state_dict()),
                            'step':step,'depth':d,'dev':metrics,
                            'dev_rank':rank})
            history.append({'phase':'self-conditioned','step':step,
                            'curriculum_depth':depth,'loss':float(loss.detach()),
                            'dev_by_depth':depth_metrics,
                            'best_step':best_step,'best_depth':best_depth})
            gauss._atomic_json(output/'history.json',{'schema':SCHEMA,'records':history})
            print(f'HYBRID_SELF step={step}/{args.steps} train_depth={depth} '
                  f'DEV_by_depth={json.dumps(depth_metrics,separators=(",",":"))} '
                  f'best={best_step}@{best_depth} loss={float(loss.detach()):.6g}', flush=True)
            _save_latest(output/'latest.pt',agent,warm_opt,self_opt,generator,
                         warm_step,self_step,best_rank,best_depth,best_step,history,identity)

    if self_step < args.steps:
        _save_latest(output/'latest.pt',agent,warm_opt,self_opt,generator,
                     warm_step,self_step,best_rank,best_depth,best_step,history,identity)
        print(f'HYBRID_PAUSED_SELF_CONDITIONED={self_step}/{args.steps}',flush=True)
        return {'status':'PAUSED_SELF_CONDITIONED','warm_step':warm_step,'self_step':self_step}
    if best_depth is None:
        raise RuntimeError('HYBRID_NO_TRAINED_DEPTH_CHECKPOINT')
    candidate=torch.load(output/'best.pt',map_location='cpu',weights_only=True)
    if candidate.get('identity')!=identity or candidate.get('step')!=best_step:
        raise RuntimeError('HYBRID_BEST_CHECKPOINT_DRIFT')
    agent.link.load_state_dict(candidate['link'])
    agent.eval()
    with torch.no_grad():
        selected_dev, selected_rank = score(agent,splits['dev'],domain,args,best_depth)
        test, test_rank = score(agent,splits['test'],domain,args,best_depth)
        control_test, control_rank = score(agent,splits['test'],domain,args,0)
        disabled_dev, disabled_rank = score(agent,splits['dev'],domain,args,best_depth,'disabled')
        shuffled_dev, shuffled_rank = score(agent,splits['dev'],domain,args,best_depth,'shuffled')
    report={
       'schema':SCHEMA+'.report', 'identity':identity,
       'activation_gate':'PASS','zero_step_parity':'PASS',
       'trained_steps':self_step,'best_step':best_step,'best_depth':best_depth,
       'baseline_DEV_min_joint5':base_rank[0],
       'selected_DEV_min_joint5':selected_rank[0],
       'selected_TEST_min_joint5':test_rank[0],
       'frozen_baseline_TEST_min_joint5':control_rank[0],
       'disabled_feedback_DEV_min_joint5':disabled_rank[0],
       'shuffled_feedback_DEV_min_joint5':shuffled_rank[0],
       'DEV_gain':selected_rank[0]-base_rank[0],
       'feedback_causally_useful_on_DEV':selected_rank[0]>max(disabled_rank[0],shuffled_rank[0]),
       'status':'LATENT_IMPROVEMENT_OBSERVED' if selected_rank[0]>base_rank[0]
                else 'NO_LATENT_GAIN_OBSERVED',
       'depths_test_evaluated_for_promotion':False,
       'TEST_used_for_training_or_promotion':False,
       'holdout_caveat':'EXPLORATORY: prior reference TEST has been inspected',
       'DEV':selected_dev, 'TEST':test}
    gauss._atomic_json(output/'report.json',report)
    print(json.dumps({'report':str(output/'report.json'),'status':report['status'],
          'best_step':best_step,'best_depth':best_depth,
          'DEV_hybrid':selected_rank[0],'TEST_hybrid':test_rank[0],
          'TEST_zero_step':control_rank[0],
          'DEV_disabled':disabled_rank[0],'DEV_shuffled':shuffled_rank[0]},indent=2),flush=True)
    return report


def parser():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--reference-checkpoint',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--device',choices=('cpu','cuda'),default='cuda')
    p.add_argument('--resume',action='store_true')
    p.add_argument('--stop-after',type=int,default=None,
        help='pause at this phase-2 step without altering the scheduled depth curriculum')
    p.add_argument('--warmup-stop-after',type=int,default=None,
        help='pause at this phase-1 step; --resume continues the SAME warmup')
    p.add_argument('--warmup-steps',type=int,default=2000)
    p.add_argument('--steps',type=int,default=12000,help='phase 2 total optimizer updates')
    p.add_argument('--probe-every',type=int,default=500)
    p.add_argument('--batch-size',type=int,default=64)
    p.add_argument('--eval-batch-size',type=int,default=256)
    p.add_argument('--seed',type=int,default=20261023)
    p.add_argument('--teacher-scale',type=float,default=.35)
    p.add_argument('--warmup-lr',type=float,default=.001)
    p.add_argument('--lr',type=float,default=.0003)
    p.add_argument('--tolerance',type=float,default=.05)
    p.add_argument('--cpu-threads',type=int,default=4)
    return p


def main(argv=None):
    return train(parser().parse_args(argv))


if __name__=='__main__':
    main()

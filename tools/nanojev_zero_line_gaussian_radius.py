SCHEMA = 'nanojev.zero-line-gaussian-radius.v1'
ARMS = ('mlp', 'gaussian', 'routed')
BANK_RADII = (16, 32, 64, 128)


def atomic_json(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + '.tmp')
    tmp.write_text(json.dumps(data, indent=2, sort_keys=True) + '\n', encoding='utf-8')
    os.replace(tmp, path)


def atomic_pt(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + '.tmp')
    torch.save(data, tmp)
    os.replace(tmp, path)


class GaussianBank(nn.Module):
    """Scale-specific Gaussian population on a SHARED learned residual coordinate.

    Centers and widths grow with radius. All banks see the same learned z,
    which is predicted from backbone state (never obtained from true delta).
    """
    def __init__(self, width, radius, centers=17, hidden=160):
        super().__init__()
        self.radius = radius
        self.register_buffer('centers', torch.linspace(-float(radius), float(radius), centers))
        self.sigma = 2. * radius / (centers - 1) * 1.5
        self.readout = nn.Sequential(nn.Linear(centers, hidden), nn.GELU(),
                                     nn.Linear(hidden, 73))
        nn.init.zeros_(self.readout[-1].weight)
        nn.init.zeros_(self.readout[-1].bias)

    def forward(self, learned_coordinate):
        population = torch.exp(-.5 * ((learned_coordinate - self.centers) / self.sigma).square())
        return self.readout(population)


class ReadoutAdapter(nn.Module):
    """Add learned corrections to *frozen* original sign/digit logits."""
    def __init__(self, width, arm, max_residual=128):
        super().__init__()
        if arm not in ARMS or max_residual not in RADII:
            raise ValueError('ZERO_BANK_BAD_ARCHITECTURE')
        self.arm = arm
        self.active_radii = tuple(r for r in BANK_RADII if r <= max_residual)
        if arm == 'mlp':
            self.mlp = nn.Sequential(nn.Linear(width, 448), nn.GELU(), nn.Linear(448, 73))
            nn.init.zeros_(self.mlp[-1].weight)
            nn.init.zeros_(self.mlp[-1].bias)
        else:
            self.latent_coordinate = nn.Linear(width, 1)
            self.banks = nn.ModuleDict({str(r): GaussianBank(width, r) for r in self.active_radii})
            if arm == 'routed':
                self.router = nn.Linear(width, len(self.active_radii))
                nn.init.zeros_(self.router.weight)
                nn.init.zeros_(self.router.bias)

    def forward(self, features, baseline_logits, stage_radius, return_weights=False):
        if self.arm == 'mlp':
            corrections = self.mlp(features)
            weights = None
        else:
            radii = [r for r in self.active_radii if r <= stage_radius]
            if not radii:
                raise ValueError('ZERO_BANK_NO_ACTIVE_BANK')
            z = self.latent_coordinate(features)  # inferred from backbone, not oracle residual
            outputs = torch.stack([self.banks[str(r)](z) for r in radii], dim=1)
            if self.arm == 'gaussian':
                weights = torch.full((len(features), len(radii)), 1. / len(radii),
                                     device=features.device, dtype=features.dtype)
            else:
                weights = torch.softmax(self.router(features)[:, :len(radii)], dim=-1)
            corrections = (outputs * weights.unsqueeze(-1)).sum(dim=1)
        logits = baseline_logits + corrections
        result = {'sign': logits[:, :3], 'digits': logits[:, 3:].reshape(-1, 7, 10)}
        return (result, weights) if return_weights else result


def trainable_count(module):
    return sum(p.numel() for p in module.parameters() if p.requires_grad)


@torch.no_grad()
def encode_base(model, operands, device, batch_size):
    """Capture recurrent query representation without modifying AdditionNet."""
    model.eval()
    encoded, logits = [], []
    slot = {}
    def capture(_module, _inputs, output):
        slot['last'] = output.detach()
    handle = model.norm.register_forward_hook(capture)
    try:
        for block in operands.split(batch_size):
            slot.clear()
            output = model(block.to(device))
            if 'last' not in slot:
                raise RuntimeError('ZERO_BANK_RECURRENT_STATE_MISSING')
            encoded.append(slot['last'].detach())
            logits.append(torch.cat((output['sign'], output['digits'].reshape(-1, 70)), -1).detach())
    finally:
        handle.remove()
    return torch.cat(encoded), torch.cat(logits)


def make_cache(model, cards, device, batch_size):
    """Purely numerical targets live outside the forward/adapter computation."""
    if isinstance(cards, dict):
        operands = cards['x'].long()
        truths = cards['y'].long()
        bands = None
    else:
        operands = torch.tensor([(a, b) for a, b, _, _, _ in cards], dtype=torch.long)
        truths = torch.tensor([d for _, _, d, _, _ in cards], dtype=torch.long)
        bands = [(b, o) for _, _, _, b, o in cards]
    latent, original_logits = encode_base(model, operands, device, batch_size)
    return {'features': latent, 'original': original_logits,
            'target': truths.to(device), 'bands': bands,
            'operands': operands}


def infer(pred):
    digits = pred['digits'].argmax(-1).long()
    powers = torch.tensor([10**i for i in range(7)], device=digits.device, dtype=torch.long)
    signs = pred['sign'].argmax(-1).long() - 1
    return (digits * powers).sum(-1) * signs, signs, digits


@torch.inference_mode()
def evaluate(adapter, cache, stage_radius, batch_size, max_delta=None, threshold=.8,
             include_cells=False, collect_routing=False, min_cell_count=6):
    adapter.eval()
    overall_correct = 0
    totals = {}
    passed = {}
    errors = {}
    routing = {}
    routing_count = {}
    for start in range(0, len(cache['target']), batch_size):
        stop = start + batch_size
        out, weights = adapter(cache['features'][start:stop], cache['original'][start:stop],
                               stage_radius, return_weights=True)
        pred, signs, digits = infer(out)
        truth = cache['target'][start:stop]
        exact = ((pred == truth) & (signs == truth.sign()) &
                 (digits == target_digits(truth)).all(-1))
        overall_correct += int(exact.sum())
        if max_delta is not None:
            for i, (delta, good, value) in enumerate(zip(truth.tolist(), exact.tolist(), pred.tolist())):
                band, orientation = cache['bands'][start+i]
                key = f'{delta}:{band}:{orientation}'
                totals[key] = totals.get(key, 0) + 1
                passed[key] = passed.get(key, 0) + int(good)
                errors[key] = errors.get(key, 0) + abs(value - delta)
        if collect_routing and weights is not None:
            for i, delta in enumerate(truth.tolist()):
                d = str(delta)
                if d not in routing:
                    routing[d] = [0.0] * weights.shape[1]
                routing_count[d] = routing_count.get(d, 0) + 1
                for k, w in enumerate(weights[i].tolist()):
                    routing[d][k] += w
    n = len(cache['target'])
    report = {'count':n, 'correct':overall_correct, 'accuracy':overall_correct/n}
    if max_delta is not None:
        cells = {key: {'count':count, 'correct':passed[key],
                       'rate':passed[key]/count, 'mae':errors[key]/count}
                 for key,count in totals.items()}
        filtered = {k:v for k,v in cells.items() if v['count'] >= min_cell_count}
        report['certified_radius'] = certify({'cells':filtered,'max_delta':max_delta},threshold)
        report['minimum_cell_samples'] = min_cell_count
        report['min_cell_rate'] = min((v['rate'] for v in cells.values()),default=0.)
        report['by_residual'] = {str(d): {'count':sum(v['count'] for k,v in cells.items()
                                                   if int(k.split(':')[0]) == d),
                                     'correct':sum(v['correct'] for k,v in cells.items()
                                                   if int(k.split(':')[0]) == d)}
                                for d in range(-max_delta, max_delta+1)}
        for value in report['by_residual'].values():
            value['accuracy'] = value['correct']/value['count'] if value['count'] else None
        if include_cells:
            report['cells'] = cells
    if collect_routing:
        report['routing_mean_by_residual'] = {d:[v/routing_count[d] for v in vals] for d,vals in routing.items()}
    return report


def write_cell_csv(path, cells):
    path=Path(path);path.parent.mkdir(parents=True,exist_ok=True)
    tmp=path.with_suffix('.tmp')
    with tmp.open('w',newline='',encoding='utf-8') as fp:
        out=csv.writer(fp)
        out.writerow(('residual','band_index','operand_orientation','n','correct','accuracy','mae'))
        for key, value in sorted(cells.items(),key=lambda kv: tuple(map(int,kv[0].split(':')))):
            d,b,o=map(int,key.split(':'))
            out.writerow((d,b,o,value['count'],value['correct'],value['rate'],value['mae']))
    os.replace(tmp,path)


def historical_batch(cache, size, rng):
    return torch.tensor([rng.randrange(len(cache['target'])) for _ in range(size)],
                        device=cache['target'].device)


def sample_pools(cache, radius):
    """Precompute CPU integer-index pools once, avoiding GPU scalar sync."""
    targets = cache['target'].detach().cpu().tolist()
    choices = [i for i, y in enumerate(targets) if abs(y) <= radius]
    center = [i for i in choices if abs(targets[i]) <= 2]
    frontier = [i for i in choices if max(2, radius//2) < abs(targets[i]) <= radius]
    if not choices or not center or not frontier:
        raise RuntimeError('ZERO_BANK_EMPTY_SAMPLE_STRATUM')
    return center, frontier, choices


def new_batch_indices(cache, radius, size, rng, pools=None):
    center, frontier, choices = pools if pools is not None else sample_pools(cache,radius)
    a = size//4
    b = size//2
    selected = ([center[rng.randrange(len(center))] for _ in range(a)] +
                [frontier[rng.randrange(len(frontier))] for _ in range(b)] +
                [choices[rng.randrange(len(choices))] for _ in range(size-a-b)])
    rng.shuffle(selected)
    return torch.tensor(selected,device=cache['target'].device)


def supervised_loss(adapter, new_cache, old_cache, radius, batch_size, rng,
                    old_fraction=.5, distill_weight=1., pools=None):
    old_size=max(1,round(batch_size*old_fraction))
    new_size=batch_size-old_size
    if new_size<1: raise ValueError('ZERO_BANK_NO_NEW_TRAINING')
    ni=new_batch_indices(new_cache,radius,new_size,rng,pools)
    oi=historical_batch(old_cache,old_size,rng)
    feats = torch.cat((new_cache['features'][ni], old_cache['features'][oi]),0)
    originals = torch.cat((new_cache['original'][ni], old_cache['original'][oi]),0)
    truths = torch.cat((new_cache['target'][ni],old_cache['target'][oi]),0)
    prediction = adapter(feats,originals,radius)
    sign_loss=F.cross_entropy(prediction['sign'],truths.sign()+1)
    digit_loss=F.cross_entropy(prediction['digits'].transpose(1,2), target_digits(truths))
    # Protect old *distributions*, not just old top-1 answers.
    def kl(student, teacher):
        return F.kl_div(F.log_softmax(student,dim=-1),F.softmax(teacher,dim=-1),reduction='batchmean')
    historical = slice(new_size,None)
    keep_sign=kl(prediction['sign'][historical],originals[historical,:3])
    keep_digits=kl(prediction['digits'][historical].reshape(-1,10),
                   originals[historical,3:].reshape(-1,10))
    return sign_loss+2*digit_loss+distill_weight*(keep_sign+keep_digits)


def checkpoint_payload(adapter, optimizer, stage_index, stage_step, rng, history, source, config_hash):
    return {'schema':SCHEMA+'.checkpoint','adapter':adapter.state_dict(),
            'optimizer':optimizer.state_dict(),'stage_index':stage_index,'stage_step':stage_step,
            'rng':rng.getstate(),'torch_rng':torch.get_rng_state(),
            'cuda_rng':torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None,
            'source_sha256':source['checkpoint_sha256'],'config_hash':config_hash,
            'history':history}


def config_hash(config):
    return hashlib.sha256(json.dumps(config,sort_keys=True).encode()).hexdigest()


def run(args):
    if args.device == 'cuda' and not torch.cuda.is_available():
        raise RuntimeError('ZERO_BANK_CUDA_UNAVAILABLE')
    if (args.max_residual not in RADII or args.steps_per_stage<1 or args.probe_every<1 or
            args.batch_size<4 or args.eval_batch_size<1 or not 0<args.lr<1 or
            not 0<args.threshold<=1 or not 0<args.old_fraction<1 or
            not 0<=args.distill_weight or args.train_per_cell<1 or args.dev_per_cell<1 or
            args.ood_per_cell<1 or args.cpu_threads<1 or args.min_cell_count<1):
        raise ValueError('ZERO_BANK_BAD_OPTIONS')
    arms = tuple(x.strip() for x in args.arms.split(',') if x.strip())
    if not arms or len(set(arms))!=len(arms) or any(a not in ARMS for a in arms):
        raise ValueError('ZERO_BANK_BAD_ARMS')
    torch.set_num_threads(args.cpu_threads)
    root = Path(args.output).expanduser().resolve()
    source_root = Path(args.ladder_output).expanduser().resolve()
    if root==source_root or root in source_root.parents or source_root in root.parents:
        raise RuntimeError('ZERO_BANK_SOURCE_OVERLAP')
    if root.exists() and any(root.iterdir()) and not args.resume:
        raise FileExistsError('ZERO_BANK_OUTPUT_EXISTS')
    model,source = load_certified_model(source_root,args.device)
    for p in model.parameters(): p.requires_grad_(False)
    source_param_hash={k:v.detach().cpu().clone() for k,v in model.state_dict().items()}
    width=int(model.query.shape[0])
    cards_train=sampled_cards(args.max_residual,TRAIN_BANDS,args.seed,'train',args.train_per_cell)
    cards_dev=sampled_cards(args.max_residual,TRAIN_BANDS,args.seed,'dev',args.dev_per_cell)
    cards_ood=sampled_cards(args.max_residual,OOD_BANDS,args.seed,'ood',args.ood_per_cell)
    if not all((cards_train,cards_dev,cards_ood)):
        raise RuntimeError('ZERO_BANK_EMPTY_DATASET')
    # Caching frozen activations prevents any accidental backbone optimization.
    known = make_cache(model,deck(127),args.device,args.eval_batch_size)
    train = make_cache(model,cards_train,args.device,args.eval_batch_size)
    dev = make_cache(model,cards_dev,args.device,args.eval_batch_size)
    ood = make_cache(model,cards_ood,args.device,args.eval_batch_size)
    config={'schema':SCHEMA,'source_sha256':source['checkpoint_sha256'],
            'arms':list(arms),'script_sha256':sha256(__file__),'max_residual':args.max_residual,'seed':args.seed,
            'train_per_cell':args.train_per_cell,'dev_per_cell':args.dev_per_cell,
            'ood_per_cell':args.ood_per_cell,'steps_per_stage':args.steps_per_stage,
            'probe_every':args.probe_every,'batch_size':args.batch_size,
            'threshold':args.threshold,'old_fraction':args.old_fraction,
            'distill_weight':args.distill_weight,'lr':args.lr,'min_cell_count':args.min_cell_count}
    fingerprint=config_hash(config)
    if args.resume:
        if json.loads((root/'config.json').read_text())!=config:
            raise RuntimeError('ZERO_BANK_CONFIG_DRIFT')
    else:
        root.mkdir(parents=True,exist_ok=True)
        atomic_json(root/'config.json',config)
    stages=[r for r in BANK_RADII if r<=args.max_residual]
    results={}
    for arm in arms:
        path = root/'arms'/arm
        if not args.resume: path.mkdir(parents=True,exist_ok=True)
        torch.manual_seed(args.seed+150)
        adapter=ReadoutAdapter(width,arm,args.max_residual).to(args.device)
        optim=torch.optim.AdamW(adapter.parameters(),lr=args.lr,weight_decay=0.)
        rng=random.Random(args.seed+1100)
        idx,step,history=0,0,[]
        arm_resuming=args.resume and (path/'latest.pt').is_file()
        if arm_resuming:
            ckpt=torch.load(path/'latest.pt',map_location='cpu',weights_only=True)
            if (ckpt.get('schema')!=SCHEMA+'.checkpoint' or
                    ckpt.get('source_sha256')!=source['checkpoint_sha256'] or
                    ckpt.get('config_hash')!=fingerprint):
                raise RuntimeError('ZERO_BANK_RESUME_SOURCE_MISMATCH')
            adapter.load_state_dict(ckpt['adapter'])
            optim.load_state_dict(ckpt['optimizer'])
            rng.setstate(ckpt['rng']);torch.set_rng_state(ckpt['torch_rng'])
            if ckpt['cuda_rng'] is not None and torch.cuda.is_available():
                torch.cuda.set_rng_state_all(ckpt['cuda_rng'])
            idx,step,history=ckpt['stage_index'],ckpt['stage_step'],ckpt['history']
        if not arm_resuming:
            baseline_dev=evaluate(adapter,dev,16,args.eval_batch_size,args.max_residual,args.threshold,min_cell_count=args.min_cell_count)
            baseline_ood=evaluate(adapter,ood,16,args.eval_batch_size,args.max_residual,args.threshold,min_cell_count=args.min_cell_count)
            baseline_old=evaluate(adapter,known,16,args.eval_batch_size)
            atomic_json(path/'baseline.json',{'dev':baseline_dev,'ood':baseline_ood,
                                              'retention':baseline_old,'parameter_count':trainable_count(adapter)})
        for j in range(idx,len(stages)):
            radius=stages[j]
            pools=sample_pools(train,radius)
            if j!=idx: step=0
            for t in range(step+1,args.steps_per_stage+1):
                adapter.train()
                loss=supervised_loss(adapter,train,known,radius,args.batch_size,rng,
                                     args.old_fraction,args.distill_weight,pools)
                optim.zero_grad(set_to_none=True)
                loss.backward()
                nn.utils.clip_grad_norm_(adapter.parameters(),1.,error_if_nonfinite=True)
                optim.step()
                if t%args.probe_every and t!=args.steps_per_stage: continue
                vd=evaluate(adapter,dev,radius,args.eval_batch_size,args.max_residual,args.threshold,
                            include_cells=t==args.steps_per_stage,
                            collect_routing=t==args.steps_per_stage,min_cell_count=args.min_cell_count)
                od=evaluate(adapter,ood,radius,args.eval_batch_size,args.max_residual,args.threshold,
                            include_cells=t==args.steps_per_stage,
                            collect_routing=t==args.steps_per_stage,min_cell_count=args.min_cell_count)
                old=evaluate(adapter,known,radius,args.eval_batch_size)
                if t==args.steps_per_stage:
                    if 'routing_mean_by_residual' in vd:
                        atomic_json(path/f'stage_{radius}_routing.json', vd.pop('routing_mean_by_residual'))
                    od.pop('routing_mean_by_residual',None)
                    write_cell_csv(path/f'stage_{radius}_dev_cells.csv',vd.pop('cells'))
                    write_cell_csv(path/f'stage_{radius}_ood_cells.csv',od.pop('cells'))
                candidate={'stage':radius,'step':t,'loss':float(loss.detach()),
                           'dev_radius':vd['certified_radius'],'ood_radius':od['certified_radius'],
                           'dev_accuracy':vd['accuracy'],'ood_accuracy':od['accuracy'],
                           'retained_count':old['correct'],'retention':old['accuracy'],
                           'source':source['checkpoint_sha256']}
                history.append(candidate)
                # Fail closed: a candidate is eligible only with full old mastery.
                baseline=json.loads((path/'baseline.json').read_text())
                eligible=(old['correct']==old['count'] and
                          vd['certified_radius']>baseline['dev']['certified_radius'] and
                          od['certified_radius']>=baseline['ood']['certified_radius'] and
                          od['accuracy']>=baseline['ood']['accuracy'])
                candidate['eligible']=bool(eligible)
                if eligible:
                    old_best=path/'best.json'
                    prior=json.loads(old_best.read_text()) if old_best.exists() else None
                    rank=(vd['certified_radius'],od['certified_radius'],vd['accuracy'])
                    prev_rank=(-1,-1.,-1.) if prior is None else tuple(prior['rank'])
                    if rank>prev_rank:
                        atomic_pt(path/'best.pt',checkpoint_payload(adapter,optim,j,t,rng,history,source,fingerprint))
                        atomic_json(path/'best.json',{'rank':rank,'candidate':candidate})
                atomic_pt(path/'latest.pt',checkpoint_payload(adapter,optim,j,t,rng,history,source,fingerprint))
                atomic_json(path/'result.json',{'schema':SCHEMA,'arm':arm,'baseline':'baseline.json',
                                                'latest':candidate,'history':history,
                                                'source':source,'TEST':None,
                                                'backbone_frozen':True,'original_head_frozen':True})
                print(f'ZERO_BANK arm={arm} stage=±{radius} step={t}/{args.steps_per_stage} '
                      f'loss={float(loss.detach()):.4f} DEV_r={vd["certified_radius"]} OOD_r={od["certified_radius"]} '
                      f'DEV={vd["accuracy"]:.4f} OOD={od["accuracy"]:.4f} '
                      f'retain={old["accuracy"]:.5f} eligible={int(eligible)}',flush=True)
            atomic_pt(path/'latest.pt',checkpoint_payload(adapter,optim,j+1,0,rng,history,source,fingerprint))
            step=0
        final={'arm':arm,'parameter_count':trainable_count(adapter),'source_sha256':source['checkpoint_sha256'],
               'best_available':(path/'best.pt').is_file(),'last':history[-1] if history else None}
        atomic_json(path/'summary.json',final)
        results[arm]=final
    if sha256(source['checkpoint']) != source['checkpoint_sha256']:
        raise RuntimeError('ZERO_BANK_SOURCE_CHANGED')
    for k,v in model.state_dict().items():
        if not torch.equal(v.detach().cpu(),source_param_hash[k]):
            raise RuntimeError('ZERO_BANK_FROZEN_MODEL_MUTATED')
    atomic_json(root/'result.json',{'schema':SCHEMA,'results':results,'source':source,
                                     'TEST':None,'source_immutable':True})
    print('ZERO_BANK_SUMMARY='+json.dumps(results),flush=True)
    print('ZERO_BANK_SOURCE_IMMUTABLE=TRUE BACKBONE_FROZEN=TRUE ORIGINAL_HEAD_FROZEN=TRUE TEST_UNTOUCHED=TRUE')
    return results


def parser():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--ladder-output',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--device',choices=('cpu','cuda'),default='cuda')
    p.add_argument('--arms',default='mlp,gaussian,routed')
    p.add_argument('--max-residual',type=int,choices=RADII,default=128)
    p.add_argument('--steps-per-stage',type=int,default=750)
    p.add_argument('--probe-every',type=int,default=150)
    p.add_argument('--batch-size',type=int,default=128)
    p.add_argument('--eval-batch-size',type=int,default=512)
    p.add_argument('--train-per-cell',type=int,default=12)
    p.add_argument('--dev-per-cell',type=int,default=12)
    p.add_argument('--ood-per-cell',type=int,default=12)
    p.add_argument('--threshold',type=float,default=.8)
    p.add_argument('--min-cell-count',type=int,default=6)
    p.add_argument('--old-fraction',type=float,default=.5)

def _record_statuses(snapshot: Mapping[str, Any]) -> list[str]:
    values: list[str] = []
    for record in snapshot.get("service_records") or []:
        if not isinstance(record, Mapping):
            continue
        for key in ("status", "human_status", "humanized_status", "application_status", "health_status"):
            value = record.get(key)
            if isinstance(value, str) and value.strip():
                values.append(value.strip().lower())
    return values


def _record_running(record: Mapping[str, Any]) -> bool:
    for key in ("status", "human_status", "humanized_status", "application_status", "health_status"):
        value = record.get(key)
        if isinstance(value, str) and value.strip().lower().startswith("running"):
            return True
    return False


def _application_record(
    snapshot: Mapping[str, Any],
    application_name: str,
) -> Mapping[str, Any] | None:
    for record in snapshot.get("service_records") or []:
        if not isinstance(record, Mapping):
            continue
        path = str(record.get("path") or "")
        if not path.startswith("$.applications["):
            continue
        if record.get("name") == application_name:
            return record
    return None


def _target_materialized(snapshot: Mapping[str, Any], target_service_name: str) -> bool:
    record = _application_record(snapshot, target_service_name)
    return bool(record and _record_running(record))


def _container_name_from_finalized_compose(
    payload: Any,
    *,
    target_service_name: str,
) -> str | None:
    """Resolve the Docker container name from Coolify's finalized compose only."""
    if not isinstance(payload, Mapping):
        return None
    finalized = payload.get("docker_compose")
    if isinstance(finalized, str):
        try:
            parsed = yaml.safe_load(finalized)
        except yaml.YAMLError:
            return None
    elif isinstance(finalized, Mapping):
        parsed = finalized
    else:
        return None
    if not isinstance(parsed, Mapping):
        return None
    services = parsed.get("services")
    if not isinstance(services, Mapping):
        return None
    service = services.get(target_service_name)
    if not isinstance(service, Mapping):
        return None
    value = service.get("container_name")
    if not isinstance(value, str):
        return None
    value = value.strip()
    if not value:
        return None
    return value


def _resolve_finalized_target_container(
    *,
    controller: Any,
    service_uuid: str,
    service_name: str,
    timeout: float,
    max_response_bytes: int,
    opener: Any,
) -> tuple[str | None, dict[str, Any]]:
    endpoint = f"/api/v1/services/{urllib.parse.quote(service_uuid, safe='')}"
    response = _http(
        controller,
        "GET",
        endpoint,
        body=None,
        timeout=timeout,
        max_response_bytes=max_response_bytes,
        opener=opener,
    )
    receipt = _receipt(
        response,
        method="GET",
        endpoint=endpoint,
        service_uuid=service_uuid,
        service_name=service_name,
    )
    container_name = None
    if response.get("ok") is True:
        container_name = _container_name_from_finalized_compose(
            response.get("payload"),
            target_service_name=service_name,
        )
    receipt["container_name"] = container_name
    finalized = response.get("payload")
    if isinstance(finalized, Mapping):
        compose = finalized.get("docker_compose")
        if isinstance(compose, str):
            receipt["finalized_compose_sha256"] = hashlib.sha256(
                compose.encode("utf-8")
            ).hexdigest()
    return container_name, receipt


def _logs_excerpt(value: Any, *, limit: int = 24000) -> str | None:
    if not isinstance(value, str):
        return None
    if len(value) <= limit:
        return value
    half = limit // 2
    return value[:half] + "\n...<truncated>...\n" + value[-half:]


def _runtime_logs(
    *,
    controller: Any,
    service_uuid: str,
    service_name: str,
    service_detail_payload: Any,
    timeout: float,
    max_response_bytes: int,
    opener: Any,
    application_name: str | None = None,
) -> dict[str, Any]:
    expected_application_name = application_name or service_name
    diagnostics = lifecycle._service_subresource_diagnostics(
        service_detail_payload,
        expected_application_name,
    )
    sub_service_name = diagnostics.get("selected_sub_service_name")
    application_uuid = diagnostics.get("selected_application_uuid")
    candidates: list[tuple[str, str]] = []
    if isinstance(application_uuid, str) and application_uuid:
        quoted_service = urllib.parse.quote(service_uuid, safe="")
        quoted_application = urllib.parse.quote(application_uuid, safe="")
        candidates.extend(
            [
                (
                    "service-application",
                    f"/api/v1/services/{quoted_service}/applications/{quoted_application}/logs?lines=300&show_timestamps=true",
                ),
                (
                    "application-resource",
                    f"/api/v1/applications/{quoted_application}/logs?lines=300",
                ),
            ]
        )
    if isinstance(sub_service_name, str) and sub_service_name:
        candidates.append(
            (
                "parent-service",
                f"/api/v1/services/{urllib.parse.quote(service_uuid, safe='')}/logs"
                f"?sub_service_name={urllib.parse.quote(sub_service_name, safe='')}"
                "&lines=300&show_timestamps=true",
            )
        )

    attempts: list[dict[str, Any]] = []
    for kind, endpoint in candidates:
        response = _http(
            controller,
            "GET",
            endpoint,
            body=None,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            opener=opener,
        )
        payload = response.get("payload")
        logs = payload.get("logs") if isinstance(payload, Mapping) else None
        item = _receipt(response, method="GET", endpoint=endpoint)
        item["endpoint_kind"] = kind
        item["logs"] = _logs_excerpt(logs)
        attempts.append(item)
        if response.get("status") == 200:
            break

    return {
        "expected_application_name": expected_application_name,
        "selected_sub_service_name": sub_service_name,
        "selected_application_uuid": application_uuid,
        "attempts": attempts,
    }



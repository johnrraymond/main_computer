def _wait_for_service_health(
    *,
    controller: Any,
    service_uuid: str,
    service_name: str,
    timeout: float,
    max_response_bytes: int,
    wait_seconds: float,
    poll_interval_seconds: float,
    opener: Any,
    sleeper: Callable[[float], None],
    controller_id: str,
    controller_meta: Mapping[str, Any],
    transition_diagnostics: bool,
) -> tuple[bool, list[dict[str, Any]], list[dict[str, Any]]]:
    started = time.monotonic()
    polls: list[dict[str, Any]] = []
    diagnostics: list[dict[str, Any]] = []
    previous: tuple[str, tuple[str, ...]] | None = None
    while True:
        _response, snapshot = _detail(
            controller=controller,
            service_uuid=service_uuid,
            service_name=service_name,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            opener=opener,
            label="stress-writer-health-poll",
        )
        poll = {
            "observed_at": snapshot.get("observed_at"),
            "service_status": snapshot.get("service_status"),
            "service_detail_snapshot": snapshot,
        }
        polls.append(poll)

        signature = _status_signature(snapshot)
        if transition_diagnostics and signature != previous:
            diagnostics.append(
                _capture_diagnostics(
                    controller=controller,
                    controller_id=controller_id,
                    controller_meta=controller_meta,
                    service_uuid=service_uuid,
                    service_name=service_name,
                    timeout=timeout,
                    max_response_bytes=max_response_bytes,
                    opener=opener,
                    reason=f"status-transition-{len(diagnostics) + 1}",
                )
            )
            previous = signature

        if bootnode._healthy_status(str(snapshot.get("service_status") or "")):
            return True, polls, diagnostics
        if time.monotonic() - started >= wait_seconds:
            return False, polls, diagnostics
        sleeper(poll_interval_seconds)



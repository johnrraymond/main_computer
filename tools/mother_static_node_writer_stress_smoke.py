def _decode_observer_b64(value: str | None) -> str | None:
    if not value:
        return None
    try:
        return base64.b64decode(value.encode("ascii"), validate=False).decode(
            "utf-8",
            errors="replace",
        )
    except Exception:
        return None


def _observer_log_text(runtime_logs: Mapping[str, Any]) -> str:
    chunks: list[str] = []
    for attempt in runtime_logs.get("attempts") or []:
        if not isinstance(attempt, Mapping):
            continue
        logs = attempt.get("logs")
        if isinstance(logs, str) and logs:
            chunks.append(logs)
    return "\n".join(chunks)


def _parse_observer_logs(logs_text: str) -> dict[str, Any]:
    events: list[dict[str, Any]] = []
    proof_files: dict[str, str] = {}
    writer_logs: list[str] = []
    for raw_line in logs_text.splitlines():
        marker_at = raw_line.find(OBSERVER_LOG_MARKER)
        if marker_at < 0:
            continue
        line = raw_line[marker_at:]
        fields: dict[str, str] = {}
        for token in line.split()[1:]:
            if "=" not in token:
                continue
            key, value = token.split("=", 1)
            fields[key] = value
        if not fields:
            continue
        event: dict[str, Any] = dict(fields)
        if "state_b64" in fields:
            event["state_json"] = _decode_observer_b64(fields.get("state_b64"))
        if fields.get("phase") == "writer-logs":
            decoded = _decode_observer_b64(fields.get("content_b64"))
            event["content"] = decoded
            if decoded is not None:
                writer_logs.append(decoded)
        if fields.get("phase") == "proof":
            file_name = fields.get("file")
            decoded = _decode_observer_b64(fields.get("content_b64"))
            event["content"] = decoded
            if file_name and decoded is not None:
                proof_files[file_name] = decoded
        events.append(event)
    return {
        "events": events,
        "proof_files": proof_files,
        "writer_logs": writer_logs,
    }


def _capture_observer(
    *,
    controller: Any,
    service_uuid: str,
    service_name: str,
    timeout: float,
    max_response_bytes: int,
    opener: Any,
    reason: str,
) -> dict[str, Any]:
    response, snapshot = _detail(
        controller=controller,
        service_uuid=service_uuid,
        service_name=service_name,
        timeout=timeout,
        max_response_bytes=max_response_bytes,
        opener=opener,
        label=f"stress-observer-{reason}",
    )
    runtime_logs = _runtime_logs(
        controller=controller,
        service_uuid=service_uuid,
        service_name=service_name,
        service_detail_payload=response.get("payload"),
        timeout=timeout,
        max_response_bytes=max_response_bytes,
        opener=opener,
        application_name=service_name,
    )
    logs_text = _observer_log_text(runtime_logs)
    return {
        "captured_at": _utc_now(),
        "reason": reason,
        "service_uuid": service_uuid,
        "service_name": service_name,
        "service_detail_snapshot": snapshot,
        "runtime_logs": runtime_logs,
        "parsed": _parse_observer_logs(logs_text),
    }



def _observer_script(writer_service_name: str) -> str:
    writer_service_name = _name(writer_service_name, "writer_service_name")
    marker = OBSERVER_LOG_MARKER
    lines = [
        "set -u",
        f"marker={bootnode._single_quote(marker)}",
        f"writer_service={bootnode._single_quote(writer_service_name)}",
        "last_state_key=''",
        'emit_file() {',
        '  label="$1"',
        '  path="$2"',
        '  tmp="/tmp/mother-writer-observer-$$-$label"',
        '  rm -f "$tmp"',
        '  if docker cp "$cid:$path" "$tmp" >/dev/null 2>&1; then',
        '    content_b64="$(base64 "$tmp" 2>/dev/null | tr -d \'\\n\' || true)"',
        '    printf \'%s phase=proof file=%s content_b64=%s\\n\' "$marker" "$label" "$content_b64"',
        '    rm -f "$tmp"',
        '  fi',
        '}',
        'printf \'%s phase=observer-start writer_service=%s\\n\' "$marker" "$writer_service"',
        "while true; do",
        '  cid="$(docker ps -aq --filter "label=com.docker.compose.service=$writer_service" 2>/dev/null | head -n 1 || true)"',
        '  if [ -z "$cid" ]; then',
        '    if [ "$last_state_key" != "missing" ]; then',
        '      printf \'%s phase=writer-container-missing writer_service=%s\\n\' "$marker" "$writer_service"',
        '      last_state_key="missing"',
        '    fi',
        '    sleep 1',
        '    continue',
        '  fi',
        '  state="$(docker inspect -f \'{{.State.Status}}\' "$cid" 2>/dev/null || true)"',
        '  exit_code="$(docker inspect -f \'{{.State.ExitCode}}\' "$cid" 2>/dev/null || true)"',
        '  oom_killed="$(docker inspect -f \'{{.State.OOMKilled}}\' "$cid" 2>/dev/null || true)"',
        '  state_json="$(docker inspect -f \'{{json .State}}\' "$cid" 2>/dev/null || true)"',
        '  state_b64="$(printf \'%s\' "$state_json" | base64 2>/dev/null | tr -d \'\\n\' || true)"',
        '  state_key="$cid|$state|$exit_code|$oom_killed"',
        '  if [ "$state_key" != "$last_state_key" ]; then',
        '    printf \'%s phase=writer-state cid=%s status=%s exit_code=%s oom_killed=%s state_b64=%s\\n\' "$marker" "$cid" "$state" "$exit_code" "$oom_killed" "$state_b64"',
        '    logs_b64="$(docker logs "$cid" 2>&1 | tail -n 300 | base64 2>/dev/null | tr -d \'\\n\' || true)"',
        '    printf \'%s phase=writer-logs cid=%s content_b64=%s\\n\' "$marker" "$cid" "$logs_b64"',
        '    emit_file result.json /proof/result.json',
        '    emit_file failed.json /proof/failed.json',
        '    emit_file docker-stderr.txt /proof/docker-stderr.txt',
        '    emit_file docker-stdout.txt /proof/docker-stdout.txt',
        '    if docker cp "$cid:/proof/healthy" "/tmp/mother-writer-observer-$$-healthy" >/dev/null 2>&1; then',
        '      printf \'%s phase=proof file=healthy content_b64=\\n\' "$marker"',
        '      rm -f "/tmp/mother-writer-observer-$$-healthy"',
        '    fi',
        '    last_state_key="$state_key"',
        '  fi',
        '  sleep 1',
        "done",
        "",
    ]
    return "\n".join(lines)



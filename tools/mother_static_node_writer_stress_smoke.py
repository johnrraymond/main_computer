#!/usr/bin/env python3
"""API-only stress smoke for Mother's temporary static-node writer pathway.

This live diagnostic intentionally reproduces the boundary exercised by
``tools/mother_bootnode_precleanup.py`` without SSH, SCP, host-shell access, or
local Docker access.

Each iteration uses only the configured Coolify HTTP API to:

1. create a disposable target service on the selected controller;
2. wait until its target container is materialized;
3. create a separate long-lived observer service that watches Docker state and
   proof files for the uniquely named writer container;
4. create the exact production ``docker:27-cli`` writer compose generated by
   ``mother_bootnode_precleanup._writer_service_compose`` without modifying it;
5. start the writer through ``POST /api/v1/services/<uuid>/start``;
6. poll service/application state and capture runtime logs, deployment matches,
   server-resource matches, and observer evidence on failure;
7. verify the write through an API-visible verifier sidecar sharing the target
   volume; and
8. delete successful disposable services.

On the first failure, diagnostic evidence is captured before deletion and the
failed writer, observer, and target are preserved by default.
"""


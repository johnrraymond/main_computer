def _utc_now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _stamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ").lower()


def _name(value: str, label: str) -> str:
    if _SAFE_NAME.fullmatch(value) is None:
        raise WriterStressSmokeError(f"{label} must match {_SAFE_NAME.pattern}")
    return value


def _iteration_name(prefix: str, iteration: int) -> str:
    suffix = f"{_stamp()}-{iteration:03d}"
    room = 63 - len(suffix) - 1
    base = prefix[:room].rstrip("-")
    return _name(f"{base}-{suffix}", "generated service name")


def _atomic_write_json(path: Path, value: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(tmp, path)



def _run_iteration(
    *,
    iteration: int,
    controller: Any,
    controller_id: str,
    controller_meta: Mapping[str, Any],
    network: str,
    environment_uuid: str,
    timeout: float,
    max_response_bytes: int,
    target_wait_seconds: float,
    writer_wait_seconds: float,
    verify_wait_seconds: float,
    poll_interval_seconds: float,
    opener: Any,
    sleeper: Callable[[float], None],
    cleanup_failed: bool,
) -> dict[str, Any]:
    target_service_name = _iteration_name("mother-writer-stress-target", iteration)
    requested_target_container = _iteration_name("mother-writer-stress-container", iteration)
    writer_service_name = _iteration_name("mother-static-node-writer-stress", iteration)
    observer_service_name = _iteration_name("mother-writer-stress-observer", iteration)
    provisional_action = _build_action(
        iteration=iteration,
        target_container=requested_target_container,
        controller_id=controller_id,
    )
    target_compose = _target_compose(
        target_service_name=target_service_name,
        target_container=requested_target_container,
        expected_sha256=provisional_action["static_nodes_sha256"],
    )
    observer_compose = _observer_compose(
        observer_service_name=observer_service_name,
        writer_service_name=writer_service_name,
    )

    action: dict[str, Any] | None = None
    writer_compose: str | None = None
    result: dict[str, Any] = {
        "iteration": iteration,
        "started_at": _utc_now(),
        "status": "failed",
        "controller_id": controller_id,
        "target": {
            "service_name": target_service_name,
            "requested_container_name": requested_target_container,
            "container_name": None,
            "expected_static_nodes_sha256": provisional_action["static_nodes_sha256"],
            "compose_sha256": hashlib.sha256(target_compose.encode("utf-8")).hexdigest(),
        },
        "observer": {
            "service_name": observer_service_name,
            "compose_sha256": hashlib.sha256(observer_compose.encode("utf-8")).hexdigest(),
            "observer_script_sha256": hashlib.sha256(
                _observer_script(writer_service_name).encode("utf-8")
            ).hexdigest(),
            "writer_service_name": writer_service_name,
        },
        "writer": {
            "service_name": writer_service_name,
            "production_compose_unmodified": True,
        },
        "failure_signature": None,
        "diagnostics": [],
        "cleanup": [],
    }

    target_uuid: str | None = None
    observer_uuid: str | None = None
    writer_uuid: str | None = None
    failure_reason: str | None = None

    try:
        target_body = _service_body(
            controller_meta,
            network=network,
            environment_uuid=environment_uuid,
            name=target_service_name,
            compose=target_compose,
            description="Disposable API-only Mother static-node writer stress target",
        )
        target_uuid, target_create = _create_service(
            controller=controller,
            body=target_body,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            opener=opener,
        )
        result["target"]["service_uuid"] = target_uuid
        result["target"]["create"] = target_create
        if not target_uuid:
            failure_reason = "target-create-failed"
            raise WriterStressSmokeError(failure_reason)

        target_start = _start_service(
            controller=controller,
            service_uuid=target_uuid,
            service_name=target_service_name,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            opener=opener,
        )
        result["target"]["start"] = target_start
        if target_start.get("ok") is not True:
            failure_reason = "target-start-failed"
            raise WriterStressSmokeError(failure_reason)

        target_ready, target_readiness_observations = _wait_for_target_start_marker(
            controller=controller,
            service_uuid=target_uuid,
            service_name=target_service_name,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            wait_seconds=target_wait_seconds,
            poll_interval_seconds=poll_interval_seconds,
            opener=opener,
            sleeper=sleeper,
        )
        result["target"]["readiness_observations"] = target_readiness_observations
        if not target_ready:
            failure_reason = "target-start-marker-not-observed"
            result["diagnostics"].append(
                _capture_diagnostics(
                    controller=controller,
                    controller_id=controller_id,
                    controller_meta=controller_meta,
                    service_uuid=target_uuid,
                    service_name=target_service_name,
                    timeout=timeout,
                    max_response_bytes=max_response_bytes,
                    opener=opener,
                    reason=failure_reason,
                )
            )
            raise WriterStressSmokeError(failure_reason)

        resolved_target_container, target_resolution = _resolve_finalized_target_container(
            controller=controller,
            service_uuid=target_uuid,
            service_name=target_service_name,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            opener=opener,
        )
        result["target"]["container_resolution"] = target_resolution
        result["target"]["container_name"] = resolved_target_container
        if not resolved_target_container:
            failure_reason = "target-container-name-unresolved"
            result["diagnostics"].append(
                _capture_diagnostics(
                    controller=controller,
                    controller_id=controller_id,
                    controller_meta=controller_meta,
                    service_uuid=target_uuid,
                    service_name=target_service_name,
                    timeout=timeout,
                    max_response_bytes=max_response_bytes,
                    opener=opener,
                    reason=failure_reason,
                )
            )
            raise WriterStressSmokeError(failure_reason)

        action = _build_action(
            iteration=iteration,
            target_container=resolved_target_container,
            controller_id=controller_id,
        )
        # Keep this exact production-generated writer compose untouched. The
        # diagnostic observer is a separate Coolify service.
        writer_compose = bootnode._writer_service_compose(writer_service_name, action)
        result["writer"]["compose_sha256"] = hashlib.sha256(
            writer_compose.encode("utf-8")
        ).hexdigest()
        result["writer"]["writer_script_sha256"] = hashlib.sha256(
            bootnode._writer_script(action).encode("utf-8")
        ).hexdigest()
        result["writer"]["target_container_name"] = resolved_target_container

        observer_body = _service_body(
            controller_meta,
            network=network,
            environment_uuid=environment_uuid,
            name=observer_service_name,
            compose=observer_compose,
            description="API-only observer for Mother static-node writer stress smoke",
        )
        observer_uuid, observer_create = _create_service(
            controller=controller,
            body=observer_body,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            opener=opener,
        )
        result["observer"]["service_uuid"] = observer_uuid
        result["observer"]["create"] = observer_create
        if not observer_uuid:
            failure_reason = "observer-create-failed"
            raise WriterStressSmokeError(failure_reason)

        observer_start = _start_service(
            controller=controller,
            service_uuid=observer_uuid,
            service_name=observer_service_name,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            opener=opener,
        )
        result["observer"]["start"] = observer_start
        if observer_start.get("ok") is not True:
            failure_reason = "observer-start-failed"
            result["observer"]["failure_capture"] = _capture_observer(
                controller=controller,
                service_uuid=observer_uuid,
                service_name=observer_service_name,
                timeout=timeout,
                max_response_bytes=max_response_bytes,
                opener=opener,
                reason=failure_reason,
            )
            raise WriterStressSmokeError(failure_reason)

        observer_ready, observer_observations = _wait_for_observer_start_marker(
            controller=controller,
            service_uuid=observer_uuid,
            service_name=observer_service_name,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            wait_seconds=target_wait_seconds,
            poll_interval_seconds=poll_interval_seconds,
            opener=opener,
            sleeper=sleeper,
        )
        result["observer"]["readiness_observations"] = observer_observations
        if not observer_ready:
            failure_reason = "observer-start-marker-not-observed"
            result["observer"]["failure_capture"] = _capture_observer(
                controller=controller,
                service_uuid=observer_uuid,
                service_name=observer_service_name,
                timeout=timeout,
                max_response_bytes=max_response_bytes,
                opener=opener,
                reason=failure_reason,
            )
            raise WriterStressSmokeError(failure_reason)

        writer_body = _service_body(
            controller_meta,
            network=network,
            environment_uuid=environment_uuid,
            name=writer_service_name,
            compose=writer_compose,
            description="API-only Mother production-shaped static-node writer stress smoke",
        )
        writer_uuid, writer_create = _create_service(
            controller=controller,
            body=writer_body,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            opener=opener,
        )
        result["writer"]["service_uuid"] = writer_uuid
        result["writer"]["create"] = writer_create
        if not writer_uuid:
            failure_reason = "writer-create-failed"
            result["observer"]["failure_capture"] = _capture_observer(
                controller=controller,
                service_uuid=observer_uuid,
                service_name=observer_service_name,
                timeout=timeout,
                max_response_bytes=max_response_bytes,
                opener=opener,
                reason=failure_reason,
            )
            raise WriterStressSmokeError(failure_reason)

        result["diagnostics"].append(
            _capture_diagnostics(
                controller=controller,
                controller_id=controller_id,
                controller_meta=controller_meta,
                service_uuid=writer_uuid,
                service_name=writer_service_name,
                timeout=timeout,
                max_response_bytes=max_response_bytes,
                opener=opener,
                reason="writer-pre-start",
            )
        )

        writer_start = _start_service(
            controller=controller,
            service_uuid=writer_uuid,
            service_name=writer_service_name,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            opener=opener,
        )
        result["writer"]["start"] = writer_start
        if writer_start.get("ok") is not True:
            failure_reason = "writer-start-failed"
            final_diag = _capture_diagnostics(
                controller=controller,
                controller_id=controller_id,
                controller_meta=controller_meta,
                service_uuid=writer_uuid,
                service_name=writer_service_name,
                timeout=timeout,
                max_response_bytes=max_response_bytes,
                opener=opener,
                reason=failure_reason,
            )
            result["diagnostics"].append(final_diag)
            result["observer"]["failure_capture"] = _capture_observer(
                controller=controller,
                service_uuid=observer_uuid,
                service_name=observer_service_name,
                timeout=timeout,
                max_response_bytes=max_response_bytes,
                opener=opener,
                reason=failure_reason,
            )
            raise WriterStressSmokeError(failure_reason)

        healthy, writer_polls, transition_diagnostics = _wait_for_service_health(
            controller=controller,
            service_uuid=writer_uuid,
            service_name=writer_service_name,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            wait_seconds=writer_wait_seconds,
            poll_interval_seconds=poll_interval_seconds,
            opener=opener,
            sleeper=sleeper,
            controller_id=controller_id,
            controller_meta=controller_meta,
            transition_diagnostics=True,
        )
        result["writer"]["polls"] = writer_polls
        result["diagnostics"].extend(transition_diagnostics)

        if not healthy:
            failure_reason = "writer-not-healthy"
            final_diag = _capture_diagnostics(
                controller=controller,
                controller_id=controller_id,
                controller_meta=controller_meta,
                service_uuid=writer_uuid,
                service_name=writer_service_name,
                timeout=timeout,
                max_response_bytes=max_response_bytes,
                opener=opener,
                reason=failure_reason,
            )
            result["diagnostics"].append(final_diag)
            signature_diagnostics = [*transition_diagnostics, final_diag]
            result["failure_signature"] = _failure_signature(
                writer_polls,
                signature_diagnostics,
            )
            result["observer"]["failure_capture"] = _capture_observer(
                controller=controller,
                service_uuid=observer_uuid,
                service_name=observer_service_name,
                timeout=timeout,
                max_response_bytes=max_response_bytes,
                opener=opener,
                reason=failure_reason,
            )
            raise WriterStressSmokeError(failure_reason)

        result["failure_signature"] = _failure_signature(
            writer_polls,
            transition_diagnostics,
        )
        result["observer"]["post_writer_capture"] = _capture_observer(
            controller=controller,
            service_uuid=observer_uuid,
            service_name=observer_service_name,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            opener=opener,
            reason="writer-healthy",
        )

        verified, verify_polls = _wait_for_verifier_sha(
            controller=controller,
            service_uuid=target_uuid,
            service_name=target_service_name,
            expected_sha256=action["static_nodes_sha256"],
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            wait_seconds=verify_wait_seconds,
            poll_interval_seconds=poll_interval_seconds,
            opener=opener,
            sleeper=sleeper,
        )
        result["target"]["verification_polls"] = verify_polls
        result["target"]["write_verified_by_verifier_logs"] = verified
        if not verified:
            failure_reason = "target-write-not-verified"
            result["diagnostics"].append(
                _capture_diagnostics(
                    controller=controller,
                    controller_id=controller_id,
                    controller_meta=controller_meta,
                    service_uuid=writer_uuid,
                    service_name=writer_service_name,
                    timeout=timeout,
                    max_response_bytes=max_response_bytes,
                    opener=opener,
                    reason=failure_reason,
                )
            )
            result["diagnostics"].append(
                _capture_diagnostics(
                    controller=controller,
                    controller_id=controller_id,
                    controller_meta=controller_meta,
                    service_uuid=target_uuid,
                    service_name=target_service_name,
                    timeout=timeout,
                    max_response_bytes=max_response_bytes,
                    opener=opener,
                    reason=failure_reason,
                )
            )
            result["observer"]["failure_capture"] = _capture_observer(
                controller=controller,
                service_uuid=observer_uuid,
                service_name=observer_service_name,
                timeout=timeout,
                max_response_bytes=max_response_bytes,
                opener=opener,
                reason=failure_reason,
            )
            raise WriterStressSmokeError(failure_reason)

        result["status"] = "pass"
        result["reason"] = None
        return result
    except WriterStressSmokeError as exc:
        result["status"] = "failed"
        result["reason"] = failure_reason or str(exc)
        return result
    finally:
        should_cleanup = result.get("status") == "pass" or cleanup_failed
        if should_cleanup:
            for service_uuid, service_name, role in (
                (writer_uuid, writer_service_name, "writer"),
                (observer_uuid, observer_service_name, "observer"),
                (target_uuid, target_service_name, "target"),
            ):
                if not service_uuid:
                    continue
                result["cleanup"].append(
                    {
                        "role": role,
                        **_delete_service(
                            controller=controller,
                            service_uuid=service_uuid,
                            service_name=service_name,
                            timeout=timeout,
                            max_response_bytes=max_response_bytes,
                            opener=opener,
                        ),
                    }
                )
        else:
            result["failed_resources_preserved"] = {
                "writer_service_uuid": writer_uuid,
                "writer_service_name": writer_service_name if writer_uuid else None,
                "observer_service_uuid": observer_uuid,
                "observer_service_name": observer_service_name if observer_uuid else None,
                "target_service_uuid": target_uuid,
                "target_service_name": target_service_name if target_uuid else None,
            }
        result["completed_at"] = _utc_now()


def _failure_focus_role(result: Mapping[str, Any]) -> str:
    reason = str(result.get("reason") or "")
    resources = result.get("failed_resources_preserved")
    resources = resources if isinstance(resources, Mapping) else {}

    preferred: list[str]
    if reason.startswith("target-"):
        preferred = ["target", "writer", "observer"]
    elif reason.startswith("observer-"):
        preferred = ["observer", "writer", "target"]
    else:
        preferred = ["writer", "target", "observer"]

    for role in preferred:
        if resources.get(f"{role}_service_uuid"):
            return role
    return preferred[0]


def _host_application_names(result: Mapping[str, Any], role: str) -> list[str]:
    resource = result.get(role)
    resource = resource if isinstance(resource, Mapping) else {}
    service_name = str(resource.get("service_name") or "").strip()
    if not service_name:
        return []
    names = [service_name]
    if role == "target":
        verifier = _verifier_name(service_name)
        if verifier not in names:
            names.append(verifier)
    return names


def _host_inspection_commands(
    *,
    service_uuid: str,
    service_name: str,
    application_names: Sequence[str],
    started_at: str | None,
    completed_at: str | None,
) -> list[str]:
    # These commands are intentionally emitted for an operator who is already
    # on the Coolify host. The smoke never opens SSH or executes host commands.
    service_dir = f"/data/coolify/services/{service_uuid}"
    commands = [
        f"ls -la {service_dir}",
        f"find {service_dir} -maxdepth 2 -type f -print | sort",
        (
            f"for f in {service_dir}/docker-compose.yml {service_dir}/docker-compose.yaml; "
            'do if [ -f "$f" ]; then echo "===== $f ====="; sed -n \'1,260p\' "$f"; fi; done'
        ),
    ]
    for application_name in application_names:
        label = f"com.docker.compose.service={application_name}"
        commands.extend(
            [
                (
                    f"docker ps -a --no-trunc --filter 'label={label}' "
                    "--format '{{.ID}} {{.Names}} {{.Image}} {{.Status}}'"
                ),
                (
                    f"for cid in $(docker ps -aq --filter 'label={label}'); do "
                    'echo "===== STATE $cid ====="; '
                    "docker inspect \"$cid\" --format "
                    "'Status={{.State.Status}} ExitCode={{.State.ExitCode}} "
                    "OOMKilled={{.State.OOMKilled}} Error={{json .State.Error}} "
                    "StartedAt={{.State.StartedAt}} FinishedAt={{.State.FinishedAt}}'; "
                    'echo "===== CMD $cid ====="; '
                    "docker inspect \"$cid\" --format '{{json .Config.Cmd}}'; "
                    'echo "===== LOGS $cid ====="; '
                    'docker logs --timestamps --tail 300 "$cid" 2>&1; '
                    "done"
                ),
            ]
        )
    if started_at and completed_at:
        commands.append(
            (
                f"docker events --since '{started_at}' --until '{completed_at}' "
                "--filter type=container --format '{{json .}}' "
                f"| grep -F '{service_name}' || true"
            )
        )
        commands.append(
            (
                f"journalctl -u docker.service --since '{started_at}' --until '{completed_at}' "
                "--no-pager | tail -n 400"
            )
        )
        commands.append(
            (
                f"journalctl -u containerd.service --since '{started_at}' --until '{completed_at}' "
                "--no-pager | tail -n 400"
            )
        )
    return commands


def _build_failure_followup(
    *,
    result: Mapping[str, Any],
    evidence_path: str | Path,
    controller_id: str,
) -> dict[str, Any]:
    resources = result.get("failed_resources_preserved")
    resources = resources if isinstance(resources, Mapping) else {}
    role = _failure_focus_role(result)
    service_uuid = str(resources.get(f"{role}_service_uuid") or "").strip()
    service_name = str(resources.get(f"{role}_service_name") or "").strip()
    evidence_arg = str(evidence_path)
    per_resource: list[dict[str, str]] = []
    for candidate_role in ("target", "observer", "writer"):
        candidate_uuid = str(resources.get(f"{candidate_role}_service_uuid") or "").strip()
        if not candidate_uuid:
            continue
        per_resource.append(
            {
                "role": candidate_role,
                "service_uuid": candidate_uuid,
                "command": (
                    "python tools/mother_writer_stress_failure_twiddle.py "
                    f'--evidence "{evidence_arg}" --role {candidate_role}'
                ),
            }
        )

    followup: dict[str, Any] = {
        "preserved_failure": True,
        "controller_id": controller_id,
        "failure_reason": result.get("reason"),
        "primary_role": role,
        "twiddle": {
            "command": (
                "python tools/mother_writer_stress_failure_twiddle.py "
                f'--evidence "{evidence_arg}" --role auto'
            ),
            "per_resource": per_resource,
        },
        "coolify_host": {
            "run_on_controller_host": controller_id,
            "ssh_invoked_by_smoke": False,
            "service_uuid": service_uuid or None,
            "service_name": service_name or None,
            "service_dir": f"/data/coolify/services/{service_uuid}" if service_uuid else None,
            "commands": [],
        },
    }
    if service_uuid and service_name:
        followup["coolify_host"]["commands"] = _host_inspection_commands(
            service_uuid=service_uuid,
            service_name=service_name,
            application_names=_host_application_names(result, role),
            started_at=str(result.get("started_at") or "") or None,
            completed_at=str(result.get("completed_at") or "") or None,
        )
    return followup


def run_stress(
    *,
    network: str,
    controller_id: str,
    runtime_state_root: str | Path,
    iterations: int,
    execute: bool,
    allow_mutation: bool,
    cleanup_failed: bool,
    continue_after_failure: bool,
    timeout: float,
    max_response_bytes: int,
    target_wait_seconds: float,
    writer_wait_seconds: float,
    verify_wait_seconds: float,
    poll_interval_seconds: float,
    opener: Any = urllib.request.urlopen,
    sleeper: Callable[[float], None] = time.sleep,
) -> dict[str, Any]:
    if not execute or not allow_mutation:
        raise WriterStressSmokeError(
            "live stress requires both --execute and --allow-mutation"
        )
    if iterations < 1:
        raise WriterStressSmokeError("iterations must be >= 1")
    for label, value in (
        ("timeout", timeout),
        ("max_response_bytes", max_response_bytes),
        ("target_wait_seconds", target_wait_seconds),
        ("writer_wait_seconds", writer_wait_seconds),
        ("verify_wait_seconds", verify_wait_seconds),
        ("poll_interval_seconds", poll_interval_seconds),
    ):
        if float(value) <= 0:
            raise WriterStressSmokeError(f"{label} must be positive")

    private_state = bootnode._load_private_state(
        runtime_state_root,
        network=network,
        mode="execute",
    )
    controller = bootnode._controller(
        private_state,
        network=network,
        controller_id=controller_id,
    )
    controller_meta = bootnode._controller_config(
        private_state,
        network=network,
        controller_id=controller_id,
    )
    environment_uuid = bootnode._resolve_environment_uuid(
        controller=controller,
        controller_id=controller_id,
        project_uuid=str(controller_meta["project_uuid"]),
        expected_name=network,
        timeout=timeout,
        max_response_bytes=max_response_bytes,
        opener=opener,
        observations=[],
    )

    evidence: dict[str, Any] = {
        "kind": KIND,
        "schema_version": 2,
        "started_at": _utc_now(),
        "network": network,
        "controller_id": controller_id,
        "transport": "coolify-http-api-only",
        "ssh_used": False,
        "host_shell_used": False,
        "local_docker_used": False,
        "iterations_requested": iterations,
        "cleanup_failed": cleanup_failed,
        "continue_after_failure": continue_after_failure,
        "results": [],
    }
    root = Path(runtime_state_root) / "mother" / "evidence" / EVIDENCE_SUBDIR
    evidence_path = root / f"{_stamp()}-{controller_id}.json"

    for iteration in range(1, iterations + 1):
        item = _run_iteration(
            iteration=iteration,
            controller=controller,
            controller_id=controller_id,
            controller_meta=controller_meta,
            network=network,
            environment_uuid=environment_uuid,
            timeout=timeout,
            max_response_bytes=max_response_bytes,
            target_wait_seconds=target_wait_seconds,
            writer_wait_seconds=writer_wait_seconds,
            verify_wait_seconds=verify_wait_seconds,
            poll_interval_seconds=poll_interval_seconds,
            opener=opener,
            sleeper=sleeper,
            cleanup_failed=cleanup_failed,
        )
        evidence["results"].append(item)
        evidence["completed_iterations"] = iteration
        evidence["status"] = (
            "pass"
            if all(result.get("status") == "pass" for result in evidence["results"])
            else "failed"
        )
        evidence["completed_at"] = _utc_now()
        if item.get("status") != "pass" and item.get("failed_resources_preserved"):
            item["operator_followup"] = _build_failure_followup(
                result=item,
                evidence_path=evidence_path,
                controller_id=controller_id,
            )
        _atomic_write_json(evidence_path, evidence)
        print(
            json.dumps(
                {
                    "iteration": iteration,
                    "status": item.get("status"),
                    "reason": item.get("reason"),
                    "writer_service_uuid": item.get("writer", {}).get("service_uuid"),
                    "observer_service_uuid": item.get("observer", {}).get("service_uuid"),
                    "target_service_uuid": item.get("target", {}).get("service_uuid"),
                    "matches_observed_incident": (
                        item.get("failure_signature") or {}
                    ).get("matches_observed_incident"),
                    "evidence_path": str(evidence_path),
                    "twiddle_command": (
                        (item.get("operator_followup") or {}).get("twiddle") or {}
                    ).get("command"),
                    "coolify_host_commands": (
                        (item.get("operator_followup") or {}).get("coolify_host") or {}
                    ).get("commands"),
                },
                sort_keys=True,
            ),
            flush=True,
        )
        if item.get("status") != "pass" and not continue_after_failure:
            break

    evidence["status"] = (
        "pass"
        if evidence["results"]
        and all(result.get("status") == "pass" for result in evidence["results"])
        else "failed"
    )
    evidence["summary"] = {
        "pass_count": sum(1 for item in evidence["results"] if item.get("status") == "pass"),
        "failure_count": sum(1 for item in evidence["results"] if item.get("status") != "pass"),
        "incident_signature_count": sum(
            1
            for item in evidence["results"]
            if (item.get("failure_signature") or {}).get("matches_observed_incident") is True
        ),
        "failed_resources_preserved": any(
            bool(item.get("failed_resources_preserved"))
            for item in evidence["results"]
        ),
    }
    evidence["completed_at"] = _utc_now()
    _atomic_write_json(evidence_path, evidence)
    evidence["evidence_path"] = str(evidence_path)
    return evidence


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "API-only stress smoke for Mother's production static-node writer "
            "materialization pathway."
        )
    )
    parser.add_argument("network", nargs="?", default="mainnet")
    parser.add_argument("--controller", default="coolify-c")
    parser.add_argument("--runtime-state-root", default="runtime/state")
    parser.add_argument("--iterations", type=int, default=DEFAULT_ITERATIONS)
    parser.add_argument("--execute", action="store_true")
    parser.add_argument("--allow-mutation", action="store_true")
    parser.add_argument(
        "--cleanup-failed",
        action="store_true",
        help="delete failed writer/observer/target services; default preserves them for diagnosis",
    )
    parser.add_argument("--continue-after-failure", action="store_true")
    parser.add_argument("--timeout", type=float, default=15.0)
    parser.add_argument("--max-response-bytes", type=int, default=bootnode.DEFAULT_MAX_RESPONSE_BYTES)
    parser.add_argument("--target-wait-seconds", type=float, default=DEFAULT_TARGET_WAIT_SECONDS)
    parser.add_argument("--writer-wait-seconds", type=float, default=DEFAULT_WRITER_WAIT_SECONDS)
    parser.add_argument("--verify-wait-seconds", type=float, default=DEFAULT_VERIFY_WAIT_SECONDS)
    parser.add_argument("--poll-interval-seconds", type=float, default=DEFAULT_POLL_INTERVAL_SECONDS)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    try:
        result = run_stress(
            network=args.network,
            controller_id=args.controller,
            runtime_state_root=args.runtime_state_root,
            iterations=args.iterations,
            execute=args.execute,
            allow_mutation=args.allow_mutation,
            cleanup_failed=args.cleanup_failed,
            continue_after_failure=args.continue_after_failure,
            timeout=args.timeout,
            max_response_bytes=args.max_response_bytes,
            target_wait_seconds=args.target_wait_seconds,
            writer_wait_seconds=args.writer_wait_seconds,
            verify_wait_seconds=args.verify_wait_seconds,
            poll_interval_seconds=args.poll_interval_seconds,
        )
    except (WriterStressSmokeError, bootnode.MotherBootnodePrecleanupError) as exc:
        print(
            json.dumps(
                {
                    "status": "failed",
                    "error": str(exc),
                    "transport": "coolify-http-api-only",
                    "ssh_used": False,
                },
                indent=2,
                sort_keys=True,
            ),
            file=sys.stderr,
        )
        return 2
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0 if result.get("status") == "pass" else 1


if __name__ == "__main__":
    raise SystemExit(main())

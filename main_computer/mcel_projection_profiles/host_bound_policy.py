"""Explicit compatibility policies for existing host-bound application projections.

New applications do not need a registered policy or an application-named projector:
they must declare a surface contractId in semanticSurface instead.  These
records preserve historical generated bytes and acceptance report labels.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping

from main_computer.mcel_projection_profiles.host_bound_generic_v1 import (
    HostBoundIrProjection,
    project_host_bound_ir,
)


@dataclass(frozen=True)
class HostBoundPolicy:
    profile_id: str
    contract_id: str | None = None
    export_prefix: str | None = None
    include_invariants: bool = True
    ownership_version: str = "mcel-generic-host-bound-projection-v1"
    report_schema: str = "mcel.host-bound-candidate-projection-report.v1"
    report_version: str = "mcel-host-bound-candidate-projection-v1"
    legacy_live_app_changed_key: str | None = None


# Compatibility constants are not a projection dispatch table. Both legacy
# validators delegate file generation to project_host_bound_ir.
COMPATIBILITY_POLICIES = {
    "calculator": HostBoundPolicy(
        profile_id="mcel.calculator.host-bound-projection.v1",
        contract_id="calculator.contract.default.app-health",
        export_prefix="Calculator",
        include_invariants=False,
        ownership_version="mcel-calculator-promotion-rehearsal-v1",
        report_schema="mcel.calculator-authoritative-projection-report.v1",
        report_version="mcel-calculator-host-bound-projection-v1",
        legacy_live_app_changed_key="liveCalculatorChanged",
    ),
    "code-editor": HostBoundPolicy(
        profile_id="mcel.code-editor.host-bound-projection.v1",
        contract_id="code-editor.contract.authoring.monaco-golden-path",
        export_prefix="CodeEditor",
        ownership_version="mcel-code-editor-host-bound-projection-v1",
    ),
}


def policy_for_app(app_id: str) -> HostBoundPolicy:
    return COMPATIBILITY_POLICIES.get(
        app_id,
        HostBoundPolicy(profile_id=f"mcel.{app_id}.host-bound-projection.v1"),
    )


def project_with_policy(
    application_ir: Mapping[str, Any], *, expected_app_id: str | None = None,
) -> HostBoundIrProjection:
    app = application_ir.get("application") or {}
    app_id = str(app.get("appId") or "") if isinstance(app, Mapping) else ""
    if expected_app_id is not None and expected_app_id != app_id:
        raise ValueError(
            f"Application IR declares {app_id!r} but package identity is {expected_app_id!r}."
        )
    policy = policy_for_app(app_id)
    # The pre-existing compatibility validators retain their exact refusals.
    # They now all use the same generic projector to generate the bytes.
    if app_id == "calculator":
        from main_computer.mcel_projection_profiles.calculator_shadow_v1 import project_calculator_ir
        projected = project_calculator_ir(application_ir)
    elif app_id == "code-editor":
        from main_computer.mcel_projection_profiles.code_editor_host_bound_v1 import project_code_editor_ir
        projected = project_code_editor_ir(application_ir)
    else:
        projected = project_host_bound_ir(application_ir)
    return HostBoundIrProjection(projected.profile_id, projected.files, projected.file_hashes)

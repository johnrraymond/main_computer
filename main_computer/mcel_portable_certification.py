def canonical_bytes(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False,
                      allow_nan=False).encode('utf-8')


def sha(value: bytes) -> str:
    return 'sha256:' + hashlib.sha256(value).hexdigest()


def generated_binding(manifest: Mapping[str, Any], directory: Path) -> dict[str, Any]:
    """Fingerprint *all* generated bytes, not just the declared package root."""
    assets = manifest['assetDigests']
    if manifest.get('portableMode') is not True:
        raise ValueError('not-portable-package')
    if not isinstance(assets, dict) or not assets:
        raise ValueError('missing-generated-assets')
    for name, digest in assets.items():
        path = (directory / name).resolve()
        if not path.is_relative_to(directory.resolve()) or not path.is_file():
            raise ValueError('generated-asset-missing')
        if sha(path.read_bytes()) != digest:
            raise ValueError('generated-asset-digest-mismatch')
    return {
        'source': dict(manifest['source']),
        'assetDigests': dict(sorted(assets.items())),
        'presentationSha256': sha((directory / 'presentation.json').read_bytes()),
        'declaredIntents': list(manifest['declaredIntents']),
    }


def current_bindings(repo: Path) -> dict[str, dict[str, Any]]:
    repo = repo.resolve()
    with tempfile.TemporaryDirectory(prefix='mcel-promotion-bindings-') as tmp:
        destination = Path(tmp)
        return {
            app: generated_binding(
                build_standalone_package(repo, app, destination, portable=True),
                destination / app,
            ) for app in APP_INTENTS
        }


def _timestamp(value: Any) -> datetime | None:
    if not isinstance(value, str):
        return None
    try:
        value = value[:-1] + '+00:00' if value.endswith('Z') else value
        parsed = datetime.fromisoformat(value)
        return parsed.astimezone(timezone.utc) if parsed.tzinfo else None
    except (TypeError, ValueError, OverflowError):
        return None


def _safe_expression(text: str, *, graph: bool) -> bool:
    """Independent bounded arithmetic check, with no eval or host dependency."""
    if not isinstance(text,str) or not text or len(text)>128:
        return False
    try:
        root = ast.parse(text, mode='eval')
    except (SyntaxError, TypeError, ValueError):
        return False
    def calc(node: ast.AST, x: float) -> float:
        if isinstance(node, ast.Expression): return calc(node.body, x)
        if isinstance(node, ast.Constant) and type(node.value) in (int, float):
            return float(node.value)
        if isinstance(node, ast.Name) and graph and node.id == 'x': return x
        if isinstance(node, ast.UnaryOp) and type(node.op) in (ast.UAdd, ast.USub):
            value = calc(node.operand, x)
            return value if isinstance(node.op, ast.UAdd) else -value
        if isinstance(node, ast.BinOp) and type(node.op) in (ast.Add, ast.Sub, ast.Mult, ast.Div):
            a, b = calc(node.left, x), calc(node.right, x)
            if isinstance(node.op, ast.Add): return a+b
            if isinstance(node.op, ast.Sub): return a-b
            if isinstance(node.op, ast.Mult): return a*b
            return a/b
        raise ValueError('unsupported-arithmetic')
    try:
        cases = [(3,6), (0,0), (6,12)] if graph else [(0,5)]
        return all(math.isfinite(result := calc(root,x)) and
                   math.isclose(result,expected,abs_tol=1e-9,rel_tol=1e-9)
                   for x,expected in cases)
    except (TypeError, ValueError, OverflowError, ZeroDivisionError):
        return False


def _same_intents(value: Any, expected: frozenset[str]) -> bool:
    return isinstance(value, list) and len(value)==len(expected) and set(value)==expected


def _verify_fixture(proof: Mapping[str, Any], problems: list[str]) -> None:
    """Recheck fixture evidence independently of producer's pass flags."""
    rows=proof.get('applications')
    if not isinstance(rows,list) or len(rows)!=2 or {r.get('appId') for r in rows if isinstance(r,dict)}!=set(APP_INTENTS):
        problems.append('applications-not-exact');return
    by_id={r['appId']:r for r in rows}
    for app,expected in APP_INTENTS.items():
        row=by_id[app]
        if (row.get('status')!='pass' or row.get('ready') is not True or
            row.get('portableMode') is not True or
            not _same_intents(row.get('declaredIntents'),expected) or
            row.get('executed') != EXPECTED_EXECUTION[app] or
            row.get('distinctExecutedIntents')!=len(expected) or
            row.get('successfulCallCount')!=(11 if app=='calculator' else 10)):
            problems.append(f'{app}-intent-proof-invalid')
        if app=='code-editor':
            effects=row.get('filesystemEffects')
            if (row.get('refusals')!=[] or row.get('safetyRefusals')!=['applyReviewedPatch'] or
                row.get('sourceTextAfterProof')!='reviewed\n' or
                not isinstance(effects,list) or len(effects)!=2 or
                [e.get('intent') for e in effects] != ['saveFile','applyReviewedPatch'] or
                [e.get('path') for e in effects] != ['example.txt','example.txt'] or
                not isinstance(effects[1].get('handle'),str) or not effects[1]['handle'] or
                [e.get('beforeSha256') for e in effects] != [
                    hashlib.sha256(b'original\n').hexdigest(),hashlib.sha256(b'saved\n').hexdigest()] or
                [e.get('afterSha256') for e in effects] != [
                    hashlib.sha256(b'saved\n').hexdigest(),hashlib.sha256(b'reviewed\n').hexdigest()]):
                problems.append('code-editor-filesystem-effects-invalid')
            continue
        if (row.get('localValidated') is not True or row.get('externalProviderVerified') is not True or
            not _same_intents(row.get('refusals'),EXTERNAL) or
            not _same_intents(row.get('safetyRefusals'),EXTERNAL) or
            not _same_intents(row.get('externalInputRefusals'),EXTERNAL) or
            not _same_intents(row.get('externalSemanticChecks'),EXTERNAL)):
            problems.append('calculator-safety-or-semantic-proof-invalid')
        receipts=row.get('externalReceipts')
        backend=row.get('externalProviderReceipts')
        if (not isinstance(receipts,list) or len(receipts)!=5 or
            not isinstance(backend,list) or len(backend)!=5 or
            [r.get('intent') for r in receipts]!=[
                'askModelForExpression','askModelForGraphExpression',
                'askModelForMathicsExpression','evaluateMathics','askResultQuestion'] or
            [r.get('intent') for r in backend]!=[r.get('intent') for r in receipts]):
            problems.append('provider-receipts-missing');continue
        for r,b in zip(receipts,backend):
            intent=r['intent']; receipt=r.get('receipt',{})
            receipt=receipt if isinstance(receipt,dict) else {}
            e=receipt.get('evidence',{})
            e=e if isinstance(e,dict) else {}
            text=receipt.get('text')
            provider=receipt.get('provider')
            if (not isinstance(text,str) or not text or not isinstance(provider,str) or
                (not provider.startswith('ollama-loopback:') and intent!='evaluateMathics') or
                intent=='evaluateMathics' and provider!='mathics3-local-worker' or
                e.get('schema')!='mcel.external-provider-receipt.v1' or
                e.get('verifiedExecution') is not True or e.get('intent')!=intent or
                e.get('backend')!=provider or e.get('outputSha256')!=sha(canonical_bytes(text)).removeprefix('sha256:') or
                b.get('outputSha256')!=e.get('outputSha256') or
                b.get('inputSha256')!=e.get('inputSha256') or
                e.get('inputSha256')!=sha(canonical_bytes(EXPECTED_INPUTS[intent])).removeprefix('sha256:') or
                b.get('backend')!=provider):
                problems.append(f'{intent}-receipt-invalid')
            if intent in EXPECTED_OUTPUTS and text!=EXPECTED_OUTPUTS[intent]:
                problems.append(f'{intent}-fixture-result-invalid')
            if intent=='askModelForExpression' and not _safe_expression(text,graph=False):
                problems.append('arithmetic-fixture-invalid')
            if intent=='askModelForGraphExpression' and not _safe_expression(text,graph=True):
                problems.append('graph-fixture-invalid')
        final=row.get('calculatorFinalState')
        expected_state=dict(zip(
            ('expression','graphExpression','mathicsExpression','mathicsResult','answer'),
            (r['receipt'].get('text') for r in receipts),
        ))
        if not isinstance(final,dict) or final!=expected_state:
            problems.append('calculator-state-receipt-mismatch')
        attempts=row.get('externalModelAttempts',[])
        if (not isinstance(attempts,list) or not MODEL_INTENTS.issubset({a.get('intent') for a in attempts if isinstance(a,dict) and a.get('accepted') is True})):
            problems.append('model-attempt-evidence-missing')
        else:
            for entry in attempts:
                if not isinstance(entry,dict) or entry.get('intent') not in MODEL_INTENTS:
                    problems.append('model-attempt-invalid');continue
                if entry.get('accepted') is True:
                    matching=next((r['receipt'].get('text') for r in receipts if r['intent']==entry['intent']),None)
                    if (not isinstance(matching,str) or
                        entry.get('normalizedSha256') != sha(canonical_bytes(matching)).removeprefix('sha256:') or
                        not isinstance(entry.get('rawSha256'),str) or
                        len(entry['rawSha256']) != 64 or
                        not all(c in '0123456789abcdef' for c in entry['rawSha256']) or
                        not isinstance(entry.get('rawChars'),int) or entry['rawChars']<1 or
                        not isinstance(entry.get('rawLines'),int) or entry['rawLines']<1):
                        problems.append('accepted-model-attempt-hash-invalid')
    if (proof.get('status')!='pass' or proof.get('passed') is not True or
        proof.get('fullSemanticRuntimeProven') is not True or
        proof.get('portableLocalAndWorkspacePassed') is not True or
        proof.get('externalProviderProven') is not True or
        proof.get('liveProviderProofRequested') is not True or
        proof.get('missingExternalProviderProof') != [] or
        proof.get('reason')!='bounded-live-19-intent-semantic-fixtures-passed'):
        problems.append('top-level-fixture-verdict-not-passing')


def verify_proof(proof: Any, repo: Path, *, now: datetime | None = None,
                 max_age_hours: float = 168, expected_bindings: Mapping[str, Any] | None = None,
                 expected_provenance: Mapping[str, Any] | None = None) -> dict[str, Any]:
    """Recompute repository + generated-package authority before accepting proof."""
    problems=[]
    if not isinstance(proof,dict) or proof.get('schema')!=PROOF_SCHEMA:
        return {'status':'refused','passed':False,'reasons':['proof-schema-unsupported'],'eligibleAppIds':[]}
    now=now or datetime.now(timezone.utc)
    stamped=_timestamp(proof.get('generatedAt'))
    if stamped is None or (now-stamped).total_seconds() < -300 or (now-stamped).total_seconds() > max_age_hours*3600:
        problems.append('proof-missing-stale-or-future-timestamp')
    current=dict(expected_provenance) if expected_provenance is not None else build_repository_provenance(repo)
    declared=proof.get('repositoryProvenance')
    if not isinstance(declared,dict) or not compare_repository_provenance(declared,current).get('exact'):
        problems.append('proof-repository-provenance-mismatch')
    bindings=dict(expected_bindings) if expected_bindings is not None else current_bindings(repo)
    if proof.get('scope') != 'independent-package-domain-operations':
        problems.append('proof-scope-not-independent-package')
    rows=proof.get('applications')
    if isinstance(rows,list):
        for row in rows:
            if not isinstance(row,dict) or row.get('appId') not in APP_INTENTS:continue
            app=row['appId']
            if row.get('sourceBindings') != bindings.get(app) or row.get('packageFingerprint') != bindings.get(app,{}).get('source',{}).get('packageFingerprint'):
                problems.append(f'{app}-generated-package-binding-mismatch')
    _verify_fixture(proof,problems)
    return {'status':'pass' if not problems else 'refused','passed':not problems,
            'reasons':sorted(set(problems)),
            'eligibleAppIds':sorted(APP_INTENTS) if not problems else [],
            'repositoryFingerprint':current.get('fingerprint'),
            'packageFingerprints':{app:bindings.get(app,{}).get('source',{}).get('packageFingerprint') for app in APP_INTENTS}}


def build_certificate(proof: Any, repo: Path, *, now: datetime | None = None,
                      max_age_hours: float = 168) -> dict[str, Any]:
    verdict=verify_proof(proof,repo,now=now,max_age_hours=max_age_hours)
    return {'schema':CERTIFICATE_SCHEMA,
            'sourceProofCanonicalSha256':sha(canonical_bytes(proof)),
            'proof':proof,'verification':verdict,
            'status':verdict['status'],'passed':verdict['passed'],
            'eligibleAppIds':verdict['eligibleAppIds']}


def verify_certificate(document: Any, repo: Path, *, now: datetime | None = None,
                       max_age_hours: float = 168) -> dict[str, Any]:
    if (not isinstance(document,dict) or document.get('schema')!=CERTIFICATE_SCHEMA or
        not isinstance(document.get('proof'),dict)):
        return {'status':'refused','passed':False,'reasons':['certificate-schema-unsupported'],'eligibleAppIds':[]}
    proof=document['proof']
    try: proof_digest=sha(canonical_bytes(proof))
    except (TypeError,ValueError,OverflowError):
        return {'status':'refused','passed':False,'reasons':['certificate-proof-not-canonical'],'eligibleAppIds':[]}
    if document.get('sourceProofCanonicalSha256')!=proof_digest:
        return {'status':'refused','passed':False,'reasons':['certificate-proof-hash-mismatch'],'eligibleAppIds':[]}
    verified=verify_proof(proof,repo,now=now,max_age_hours=max_age_hours)
    if (document.get('verification')!=verified or document.get('status')!=verified['status'] or
        document.get('passed') is not verified['passed'] or
        document.get('eligibleAppIds')!=verified['eligibleAppIds']):
        return {**verified,'status':'refused','passed':False,'eligibleAppIds':[],
                'reasons':sorted(set(verified['reasons']+['certificate-verdict-mismatch']))}
    return verified
